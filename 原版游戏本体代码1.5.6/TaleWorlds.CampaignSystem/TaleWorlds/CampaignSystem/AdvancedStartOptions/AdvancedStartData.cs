using System.Collections.Generic;
using TaleWorlds.Core;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.AdvancedStartOptions;

public abstract class AdvancedStartData
{
	private const string NameTextId = "str_campaign_starting_options_name";

	private const string DescriptionTextId = "str_campaign_starting_options_description";

	private const string ItemTextId = "str_advanced_start_value_name";

	[SaveableField(1)]
	public string StringId;

	[SaveableField(2)]
	public string CategoryId;

	protected AdvancedStartData(string stringId, string categoryId)
	{
		StringId = stringId;
		CategoryId = categoryId;
	}

	public abstract object GetData();

	public abstract AdvancedStartData Clone();

	internal TextObject GetDisplayName()
	{
		object data = GetData();
		if (data != null)
		{
			if (data is string variation)
			{
				return GameTexts.FindText("str_advanced_start_value_name", variation);
			}
			object obj;
			if ((obj = data) is bool)
			{
				return new TextObject(((bool)obj) ? "1" : "0");
			}
			return new TextObject(data.ToString());
		}
		return TextObject.GetEmpty();
	}

	public TextObject GetName(GameTextManager gameTextManager)
	{
		return gameTextManager.FindText("str_campaign_starting_options_name", StringId);
	}

	public TextObject GetDescription(GameTextManager gameTextManager)
	{
		return gameTextManager.FindText("str_campaign_starting_options_description", StringId);
	}

	protected virtual void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
	}

	internal static object AutoGeneratedGetMemberValueStringId(object o)
	{
		return ((AdvancedStartData)o).StringId;
	}

	internal static object AutoGeneratedGetMemberValueCategoryId(object o)
	{
		return ((AdvancedStartData)o).CategoryId;
	}
}
public class AdvancedStartData<T> : AdvancedStartData
{
	[SaveableField(3)]
	public T Value;

	public AdvancedStartData(string stringId, string categoryId, T value)
		: base(stringId, categoryId)
	{
		Value = value;
	}

	public override object GetData()
	{
		return Value;
	}

	public override AdvancedStartData Clone()
	{
		return new AdvancedStartData<T>(StringId, CategoryId, Value);
	}

	protected override void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		base.AutoGeneratedInstanceCollectObjects(collectedObjects);
		collectedObjects.Add(Value);
	}
}
