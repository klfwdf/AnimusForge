using System;
using System.Collections.Generic;
using TaleWorlds.CampaignSystem.GameState;
using TaleWorlds.Core;
using TaleWorlds.Localization;
using TaleWorlds.ObjectSystem;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.Incidents;

public class IncidentManager
{
	[SaveableField(1)]
	private CampaignTime _lastGlobalIncidentCooldown = CampaignTime.Zero;

	[SaveableField(2)]
	private Dictionary<Incident, CampaignTime> _incidentsOnCooldown = new Dictionary<Incident, CampaignTime>();

	[SaveableField(3)]
	private long _activeIncidentSeed;

	public long ActiveIncidentSeed => _activeIncidentSeed;

	internal static void AutoGeneratedStaticCollectObjectsIncidentManager(object o, List<object> collectedObjects)
	{
		((IncidentManager)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected virtual void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		CampaignTime.AutoGeneratedStaticCollectObjectsCampaignTime(_lastGlobalIncidentCooldown, collectedObjects);
		collectedObjects.Add(_incidentsOnCooldown);
	}

	internal static object AutoGeneratedGetMemberValue_lastGlobalIncidentCooldown(object o)
	{
		return ((IncidentManager)o)._lastGlobalIncidentCooldown;
	}

	internal static object AutoGeneratedGetMemberValue_incidentsOnCooldown(object o)
	{
		return ((IncidentManager)o)._incidentsOnCooldown;
	}

	internal static object AutoGeneratedGetMemberValue_activeIncidentSeed(object o)
	{
		return ((IncidentManager)o)._activeIncidentSeed;
	}

	public void RegisterEvents()
	{
	}

	public void InitializeOnNewGame()
	{
		_lastGlobalIncidentCooldown = CampaignTime.Now + GetCooldownTime();
	}

	public void OnPlayerCharacterChange()
	{
		_lastGlobalIncidentCooldown = CampaignTime.Now + CampaignTime.Hours(1f);
		_incidentsOnCooldown.Clear();
	}

	public Incident RegisterIncident(string id, string title, string description, string triggerId, string type, CampaignTime cooldown, Func<TextObject, bool> condition)
	{
		return RegisterIncident(id, title, description, new string[1] { triggerId }, type, cooldown, condition);
	}

	public Incident RegisterIncident(string id, string title, string description, string[] triggerIds, string type, CampaignTime cooldown, Func<TextObject, bool> condition)
	{
		Incident incident = Game.Current.ObjectManager.RegisterPresumedObject(new Incident(id));
		incident.Initialize(title, description, new Incident.IncidentTrigger(triggerIds), type, cooldown, condition);
		return incident;
	}

	public void IncidentResolved(Incident incident)
	{
		if (!_incidentsOnCooldown.ContainsKey(incident))
		{
			_incidentsOnCooldown.Add(incident, CampaignTime.Now);
		}
		_lastGlobalIncidentCooldown = CampaignTime.Now + GetCooldownTime();
		CampaignEventDispatcher.Instance.OnIncidentResolved(incident);
	}

	public void TryInvokeIncident(Incident.IncidentTrigger trigger)
	{
		if (!Hero.MainHero.IsPrisoner && _lastGlobalIncidentCooldown.IsPast)
		{
			CheckIncidentsOnCooldown();
			_activeIncidentSeed = CampaignTime.Now.NumTicks;
			IReadOnlyList<Incident> occurableEventsForTrigger = GetOccurableEventsForTrigger(trigger);
			if (occurableEventsForTrigger.Count > 0)
			{
				Incident randomElement = occurableEventsForTrigger.GetRandomElement();
				InvokeIncident(randomElement);
			}
		}
	}

	private CampaignTime GetCooldownTime()
	{
		CampaignTime minGlobalCooldownTime = Campaign.Current.Models.IncidentModel.GetMinGlobalCooldownTime();
		CampaignTime maxGlobalCooldownTime = Campaign.Current.Models.IncidentModel.GetMaxGlobalCooldownTime();
		return CampaignTime.Hours(MBRandom.RandomFloatRanged((float)minGlobalCooldownTime.ToHours, (float)maxGlobalCooldownTime.ToHours));
	}

	private void CheckIncidentsOnCooldown()
	{
		List<Incident> list = new List<Incident>();
		foreach (KeyValuePair<Incident, CampaignTime> item in _incidentsOnCooldown)
		{
			if (item.Value + item.Key.Cooldown <= CampaignTime.Now)
			{
				list.Add(item.Key);
			}
		}
		foreach (Incident item2 in list)
		{
			_incidentsOnCooldown.Remove(item2);
		}
	}

	private IReadOnlyList<Incident> GetOccurableEventsForTrigger(Incident.IncidentTrigger trigger)
	{
		List<Incident> list = new List<Incident>();
		foreach (Incident objectType in MBObjectManager.Instance.GetObjectTypeList<Incident>())
		{
			if (!_incidentsOnCooldown.ContainsKey(objectType) && objectType.Trigger.HasTrigger(trigger) && objectType.CanIncidentBeInvoked())
			{
				list.Add(objectType);
			}
		}
		return list;
	}

	private void InvokeIncident(Incident incident)
	{
		MapState mapState = GameStateManager.Current.LastOrDefault<MapState>();
		if (mapState != null)
		{
			mapState.NextIncident = incident;
		}
	}
}
