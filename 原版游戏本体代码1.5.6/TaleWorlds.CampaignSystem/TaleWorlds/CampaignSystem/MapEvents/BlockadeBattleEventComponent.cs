using System.Collections.Generic;
using System.Linq;
using Helpers;
using TaleWorlds.CampaignSystem.Actions;
using TaleWorlds.CampaignSystem.Encounters;
using TaleWorlds.CampaignSystem.GameMenus;
using TaleWorlds.CampaignSystem.Naval;
using TaleWorlds.CampaignSystem.Party;
using TaleWorlds.CampaignSystem.Settlements;
using TaleWorlds.CampaignSystem.Siege;
using TaleWorlds.Core;
using TaleWorlds.Library;

namespace TaleWorlds.CampaignSystem.MapEvents;

public class BlockadeBattleEventComponent : MapEventComponent
{
	[CachedData]
	private bool _isInitializationNotFinished;

	private bool _isSallyOut;

	private bool _isSiegeCompleted;

	private bool _isSiegeWon;

	public override MapEvent.PowerCalculationContext SimulationContext => MapEvent.PowerCalculationContext.SeaBattle;

	internal static void AutoGeneratedStaticCollectObjectsBlockadeBattleEventComponent(object o, List<object> collectedObjects)
	{
		((BlockadeBattleEventComponent)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected override void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		base.AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	private BlockadeBattleEventComponent(MapEvent mapEvent)
		: base(mapEvent)
	{
		_isInitializationNotFinished = true;
	}

	public static BlockadeBattleEventComponent CreateBlockadeBattleMapEvent(PartyBase attackerParty, PartyBase besiegerParty, bool isSallyOut)
	{
		MapEvent mapEvent = new MapEvent();
		BlockadeBattleEventComponent blockadeBattleEventComponent = new BlockadeBattleEventComponent(mapEvent);
		mapEvent.Initialize(attackerParty, besiegerParty, blockadeBattleEventComponent);
		Campaign.Current.MapEventManager.OnMapEventCreated(mapEvent);
		blockadeBattleEventComponent._isSallyOut = isSallyOut;
		return blockadeBattleEventComponent;
	}

	private static float CalculateBesiegerSideNavalPower(BesiegerCamp besiegerCamp)
	{
		float num = 0f;
		foreach (PartyBase item in besiegerCamp.GetInvolvedPartiesForEventType(MapEvent.BattleTypes.BlockadeBattle))
		{
			num += item.GetCustomStrength(BattleSideEnum.Defender, MapEvent.PowerCalculationContext.SeaBattle);
		}
		return num;
	}

	private float CalculateAttackerNavalPower(PartyBase attackerParty)
	{
		float num = 0f;
		num += attackerParty.GetCustomStrength(BattleSideEnum.Attacker, SimulationContext);
		foreach (MobileParty attachedParty in attackerParty.MobileParty.AttachedParties)
		{
			num += attachedParty.Party.GetCustomStrength(BattleSideEnum.Attacker, SimulationContext);
		}
		if (base.MapEvent.EventType == MapEvent.BattleTypes.BlockadeSallyOutBattle)
		{
			foreach (PartyBase item in (attackerParty.MobileParty.CurrentSettlement ?? base.MapEvent.DefenderSide.LeaderParty.MobileParty.BesiegedSettlement).GetInvolvedPartiesForEventType(base.MapEvent.EventType))
			{
				num += item.GetCustomStrength(BattleSideEnum.Attacker, SimulationContext);
			}
		}
		return num;
	}

	public override MapEvent.BattleTypes GetBattleType()
	{
		if (!_isSallyOut)
		{
			return MapEvent.BattleTypes.BlockadeBattle;
		}
		return MapEvent.BattleTypes.BlockadeSallyOutBattle;
	}

	public override void AddNearbyPartiesToPlayerMapEvent()
	{
		MapEventComponentHelper.AddNearbyPartiesToPlayerMapEvent(base.MapEvent);
	}

	public override bool TryHandlePlayerEncounterEnd(bool isPlayerAttacker)
	{
		if (_isSallyOut)
		{
			if (!isPlayerAttacker)
			{
				EncounterManager.StartSettlementEncounter((MobileParty.MainParty.Army != null) ? MobileParty.MainParty.Army.LeaderParty : MobileParty.MainParty, base.MapEventSettlement);
				GameMenu.SwitchToMenu("menu_settlement_taken");
			}
		}
		else if (PlayerEncounter.InsideSettlement)
		{
			PlayerEncounter.LeaveSettlement();
		}
		return true;
	}

	public override PlayerEncounterState GetPlayerEncounterStateOnMapEventEnd()
	{
		if (base.MapEvent.WinningSide == PartyBase.MainParty.Side)
		{
			return PlayerEncounterState.PlayerVictory;
		}
		if (base.MapEvent.DefeatedSide == PartyBase.MainParty.Side)
		{
			return PlayerEncounterState.PlayerTotalDefeat;
		}
		return PlayerEncounterState.End;
	}

	public override bool CheckIfBattleShouldContinueAfterBattleMission(CampaignBattleResult campaignBattleResult)
	{
		return MapEventComponentHelper.CheckIfBattleShouldContinueAfterBattleMissionCommonCondition(base.MapEvent, campaignBattleResult);
	}

	public override void UpdatePlayerEncounterState(CampaignBattleResult campaignBattleResult, out PlayerEncounterState encounterState, out bool stateHandled)
	{
		MapEventComponentHelper.PlayerEncounterDoWaitCommon(base.MapEvent, campaignBattleResult, out encounterState, out stateHandled);
	}

	public override void OnPlayerEncounterContinueBattle(CampaignBattleResult campaignBattleResult, out PlayerEncounterState nextEncounterState, out bool stateHandled)
	{
		nextEncounterState = PlayerEncounter.Current.EncounterState;
		stateHandled = false;
		if (base.MapEvent.IsNavalMapEvent)
		{
			MapEventComponentHelper.OnPlayerEncounterContinueNavalBattleCommon(base.MapEvent, campaignBattleResult, out nextEncounterState);
		}
		if (nextEncounterState == PlayerEncounter.Current.EncounterState)
		{
			base.MapEvent.ApplyGainedVariablesOnPlayerBattleContinues();
			base.MapEvent.SetOverrideWinner(BattleSideEnum.None);
			stateHandled = true;
		}
	}

	public override void OnBeforeMapEventFinalize()
	{
		if (base.MapEvent.BattleState != BattleState.None && base.MapEventSettlement.SiegeEvent != null)
		{
			base.MapEventSettlement.SiegeEvent.OnBeforeSiegeEventEnd(base.MapEvent.BattleState, base.MapEvent.EventType);
		}
		if (_isSallyOut)
		{
			if (base.MapEventSettlement.Town != null && base.MapEventSettlement.Town.GarrisonParty != null && base.MapEventSettlement.Town.GarrisonParty.IsActive)
			{
				base.MapEventSettlement.Town.GarrisonParty.SetMoveModeHold();
			}
			switch (base.MapEvent.BattleState)
			{
			case BattleState.DefenderVictory:
				CampaignEventDispatcher.Instance.SiegeCompleted(base.MapEventSettlement, base.MapEvent.DefenderSide.LeaderParty.MobileParty, isWin: true, base.MapEvent.EventType);
				_isSiegeWon = true;
				break;
			case BattleState.AttackerVictory:
				base.MapEventSettlement.SiegeEvent?.BesiegerCamp.RemoveAllSiegeParties();
				CampaignEventDispatcher.Instance.SiegeCompleted(base.MapEventSettlement, base.MapEvent.DefenderSide.LeaderParty.MobileParty, isWin: false, base.MapEvent.EventType);
				break;
			}
			if (base.MapEvent.BattleState == BattleState.AttackerVictory || base.MapEvent.BattleState == BattleState.DefenderVictory)
			{
				_isSiegeCompleted = true;
			}
		}
		else
		{
			BattleState battleState = base.MapEvent.BattleState;
			if (battleState == BattleState.AttackerVictory)
			{
				base.MapEventSettlement.SiegeEvent?.BesiegerCamp.RemoveAllSiegeParties();
				CampaignEventDispatcher.Instance.SiegeCompleted(base.MapEventSettlement, base.MapEvent.DefenderSide.LeaderParty.MobileParty, isWin: false, base.MapEvent.EventType);
			}
		}
	}

	public override void OnAddInvolvedParty(MapEventParty party, BattleSideEnum side)
	{
		if (party.Party.MobileParty != null && party.Party.MobileParty.IsGarrison && side == BattleSideEnum.Attacker)
		{
			_isSallyOut = true;
			base.MapEventSettlement = party.Party.MobileParty.CurrentSettlement;
		}
	}

	public override void UpdateAfterMapChange(MobileParty.NavigationType leaderNavigationCapability, MapEvent mapEvent)
	{
		foreach (PartyBase involvedParty in mapEvent.InvolvedParties)
		{
			if (involvedParty.IsMobile && involvedParty.MobileParty.CurrentSettlement == null && involvedParty.MobileParty.BesiegerCamp == null)
			{
				involvedParty.MobileParty.SetPositionAfterMapChange(mapEvent.Position);
			}
		}
	}

	public override void AddInsideSettlementParties()
	{
		if (!_isSallyOut)
		{
			return;
		}
		List<PartyBase> list = new List<PartyBase>();
		foreach (PartyBase item in base.MapEventSettlement.GetInvolvedPartiesForEventType(base.MapEvent.EventType))
		{
			if (item != PartyBase.MainParty && item.MobileParty?.AttachedTo != MobileParty.MainParty)
			{
				list.Add(item);
			}
		}
		foreach (PartyBase item2 in list)
		{
			if (base.MapEventSettlement.SiegeEvent.CanPartyJoinSide(item2, BattleSideEnum.Defender))
			{
				item2.MapEventSide = base.MapEvent.AttackerSide;
			}
			else if (item2.MobileParty != null && !item2.MobileParty.IsGarrison && !item2.MobileParty.IsMilitia)
			{
				LeaveSettlementAction.ApplyForParty(item2.MobileParty);
				item2.MobileParty.SetMoveModeHold();
			}
		}
	}

	public override CampaignVec2 GetMapEventPosition()
	{
		return base.MapEvent.DefenderSide.LeaderParty.MobileParty.BesiegedSettlement.PortPosition;
	}

	public override void UpdateMapEventSettlement()
	{
		base.MapEventSettlement = base.MapEvent.DefenderSide.LeaderParty.MobileParty.BesiegedSettlement;
	}

	protected override MBList<Ship> GetAllAvailableSimulationShips(MapEventSide side)
	{
		MBList<Ship> mBList = new MBList<Ship>();
		foreach (MapEventParty party in side.Parties)
		{
			foreach (Ship ship in party.Ships)
			{
				mBList.Add(ship);
			}
		}
		return mBList;
	}

	public override bool CanLootDefeatedPartyShips(out bool partiallyLootShips)
	{
		partiallyLootShips = false;
		return base.MapEvent.RetreatingSide == BattleSideEnum.None;
	}

	public override void OnPlayerEncounterFinalizeBattle()
	{
		if (base.MapEvent.HasWinner || base.MapEvent.DiplomaticallyFinished)
		{
			PlayerEncounter.Current.FinalizeBattleFromComponent();
		}
		else
		{
			PlayerEncounter.LeaveBattle();
		}
	}

	protected override void OnInitialize()
	{
		if (base.MapEvent.DefenderSide.LeaderParty.MobileParty.IsMainParty)
		{
			GameMenu.ActivateGameMenu("player_blockade_got_attacked");
		}
		else
		{
			CheckLiftingBlockade();
		}
		_isInitializationNotFinished = false;
	}

	public override void OnPartyAdded(PartyBase party)
	{
		if (!_isInitializationNotFinished && !base.MapEvent.DefenderSide.LeaderParty.MobileParty.IsMainParty)
		{
			CheckLiftingBlockade();
		}
	}

	private void CheckLiftingBlockade()
	{
		if (base.MapEvent.State == MapEventState.WaitingRemoval)
		{
			return;
		}
		PartyBase leaderParty = base.MapEvent.AttackerSide.LeaderParty;
		PartyBase leaderParty2 = base.MapEvent.DefenderSide.LeaderParty;
		float num = CalculateAttackerNavalPower(leaderParty);
		float num2 = CalculateBesiegerSideNavalPower(leaderParty2.SiegeEvent.BesiegerCamp);
		if (!(num > num2 * 1.2f))
		{
			return;
		}
		leaderParty2.SiegeEvent.DeactivateBlockade();
		Settlement besiegedSettlement = leaderParty2.SiegeEvent.BesiegedSettlement;
		List<MapEventParty> list = base.MapEvent.AttackerSide.Parties.ToList();
		base.MapEvent.FinalizeEvent();
		foreach (MapEventParty item in list)
		{
			if (item.Party != PartyBase.MainParty && item.Party.IsMobile && item.Party.MobileParty.CurrentSettlement == null && item.Party.MobileParty.AttachedTo == null && item.Party.MobileParty.HasNavalNavigationCapability)
			{
				item.Party.MobileParty.SetMoveGoToSettlement(besiegedSettlement, MobileParty.NavigationType.Naval, isTargetingThePort: true);
			}
		}
	}

	protected override void OnFinalize()
	{
		if (base.MapEvent.DefeatedSide == BattleSideEnum.Defender && base.MapEvent.DefenderSide.LeaderParty.SiegeEvent != null)
		{
			base.MapEvent.DefenderSide.LeaderParty.SiegeEvent.FinalizeSiegeEvent();
		}
		if (_isSiegeCompleted)
		{
			CampaignEventDispatcher.Instance.AfterSiegeCompleted(base.MapEventSettlement, base.MapEvent.AttackerSide.LeaderParty.MobileParty, _isSiegeWon, base.MapEvent.EventType);
		}
	}
}
