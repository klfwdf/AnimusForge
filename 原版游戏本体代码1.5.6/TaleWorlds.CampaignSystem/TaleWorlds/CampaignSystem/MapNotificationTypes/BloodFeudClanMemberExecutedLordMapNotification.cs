using System.Collections.Generic;
using TaleWorlds.Core;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.MapNotificationTypes;

public class BloodFeudClanMemberExecutedLordMapNotification : InformationData
{
	[SaveableProperty(1)]
	public Hero ExecutedHero { get; private set; }

	[SaveableProperty(2)]
	public Hero Executor { get; private set; }

	[SaveableProperty(3)]
	public CampaignTime ExecutionDate { get; private set; }

	public override TextObject TitleText => new TextObject("{=1DtUj996}Clan Member Executed Lord");

	public override string SoundEventPath => "event:/ui/notification/death";

	internal static void AutoGeneratedStaticCollectObjectsBloodFeudClanMemberExecutedLordMapNotification(object o, List<object> collectedObjects)
	{
		((BloodFeudClanMemberExecutedLordMapNotification)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected override void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		base.AutoGeneratedInstanceCollectObjects(collectedObjects);
		collectedObjects.Add(ExecutedHero);
		collectedObjects.Add(Executor);
		CampaignTime.AutoGeneratedStaticCollectObjectsCampaignTime(ExecutionDate, collectedObjects);
	}

	internal static object AutoGeneratedGetMemberValueExecutedHero(object o)
	{
		return ((BloodFeudClanMemberExecutedLordMapNotification)o).ExecutedHero;
	}

	internal static object AutoGeneratedGetMemberValueExecutor(object o)
	{
		return ((BloodFeudClanMemberExecutedLordMapNotification)o).Executor;
	}

	internal static object AutoGeneratedGetMemberValueExecutionDate(object o)
	{
		return ((BloodFeudClanMemberExecutedLordMapNotification)o).ExecutionDate;
	}

	public BloodFeudClanMemberExecutedLordMapNotification(Hero executedHero, Hero executor, CampaignTime executionDate, TextObject descriptionText)
		: base(descriptionText)
	{
		ExecutedHero = executedHero;
		Executor = executor;
		ExecutionDate = executionDate;
	}

	public BloodFeudClanMemberExecutedLordMapNotification(TextObject description)
		: base(description)
	{
	}
}
