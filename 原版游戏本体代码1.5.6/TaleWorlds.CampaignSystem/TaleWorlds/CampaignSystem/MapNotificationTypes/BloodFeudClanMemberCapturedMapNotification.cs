using System.Collections.Generic;
using TaleWorlds.CampaignSystem.Settlements;
using TaleWorlds.Core;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.MapNotificationTypes;

public class BloodFeudClanMemberCapturedMapNotification : InformationData
{
	[SaveableProperty(1)]
	public Hero CaptiveHero { get; private set; }

	[SaveableProperty(2)]
	public CampaignTime ExecutionDate { get; private set; }

	[SaveableProperty(3)]
	public Settlement Settlement { get; private set; }

	public override TextObject TitleText => new TextObject("{=0QtMuKEQ}Clan Member Got Captured");

	public override string SoundEventPath => "event:/ui/notification/alert";

	internal static void AutoGeneratedStaticCollectObjectsBloodFeudClanMemberCapturedMapNotification(object o, List<object> collectedObjects)
	{
		((BloodFeudClanMemberCapturedMapNotification)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected override void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		base.AutoGeneratedInstanceCollectObjects(collectedObjects);
		collectedObjects.Add(CaptiveHero);
		CampaignTime.AutoGeneratedStaticCollectObjectsCampaignTime(ExecutionDate, collectedObjects);
		collectedObjects.Add(Settlement);
	}

	internal static object AutoGeneratedGetMemberValueCaptiveHero(object o)
	{
		return ((BloodFeudClanMemberCapturedMapNotification)o).CaptiveHero;
	}

	internal static object AutoGeneratedGetMemberValueExecutionDate(object o)
	{
		return ((BloodFeudClanMemberCapturedMapNotification)o).ExecutionDate;
	}

	internal static object AutoGeneratedGetMemberValueSettlement(object o)
	{
		return ((BloodFeudClanMemberCapturedMapNotification)o).Settlement;
	}

	public BloodFeudClanMemberCapturedMapNotification(Hero captiveHero, CampaignTime executionDate, Settlement settlement, TextObject descriptionText)
		: base(descriptionText)
	{
		CaptiveHero = captiveHero;
		ExecutionDate = executionDate;
		Settlement = settlement;
	}

	public BloodFeudClanMemberCapturedMapNotification(Hero captiveHero, TextObject descriptionText)
		: base(descriptionText)
	{
		CaptiveHero = captiveHero;
	}

	public override bool IsValid()
	{
		if (CaptiveHero.IsAlive)
		{
			return CaptiveHero.IsPrisoner;
		}
		return false;
	}
}
