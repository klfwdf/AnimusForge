        internal static string PortraitFraming(int sequence)
        {
            switch ((sequence < 1 ? 0 : sequence - 1) % 3)
            {
                case 0: return "近景半身肖像：头顶至腰部入镜，完整保留头戴与肩甲；人物约占画幅三分之二，两侧与肩后留出可辨认的环境空间，背景不可压黑。";
                case 1: return "轻微侧身的近景半身肖像：头顶至胸腹部入镜，手部可自然在画外；面部与实际衣甲清晰，背景的纵深、材质与环境色必须可辨，不靠复杂姿势变化。";
                default: return "中景环境半身肖像：完整头戴到腰部入镜，给可辨认的背景空间留出更多画幅；前景轻微虚化、中景人物清楚、后景仍有形体和明暗层次，不画全黑背景。";
            }
        }

