using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using BUTR.CrashReport.Interfaces;
using BUTR.CrashReport.Models;
using Bannerlord.ButterLib.SubModuleWrappers2;
using Bannerlord.ButterLib.SubModuleWrappers2.Patches;

namespace Bannerlord.ButterLib.ExceptionHandler.Utils;

internal class StacktraceFilter : IStacktraceFilter
{
	private readonly MethodInfo? _bewFinalizer;

	public StacktraceFilter(MethodInfo? bewFinalizer)
	{
		_bewFinalizer = bewFinalizer;
	}

	public IEnumerable<StacktraceEntry> Filter(ICollection<StacktraceEntry> stacktraceEntries)
	{
		if (stacktraceEntries.Count == 1 && stacktraceEntries.First().ModuleInfo?.Id == "Bannerlord.Harmony")
		{
			yield break;
		}
		foreach (StacktraceEntry stacktraceEntry in stacktraceEntries)
		{
			if (stacktraceEntry.ModuleInfo?.Id == "Bannerlord.ButterLib" && (stacktraceEntry.Method == _bewFinalizer || stacktraceEntry.Method.DeclaringType == typeof(MBSubModuleBaseWrapper) || stacktraceEntry.Method.DeclaringType == typeof(MBSubModuleBaseListWrapper) || stacktraceEntry.Method.DeclaringType == typeof(MBSubModuleBasePatch)))
			{
				continue;
			}
			if (stacktraceEntry.ModuleInfo?.Id == "BetterExceptionWindow")
			{
				MethodBase method = stacktraceEntry.Method;
				if ((object)method != null && method.Name == "Finalizer")
				{
					Type declaringType = method.DeclaringType;
					if ((object)declaringType != null && declaringType.Name == "AutoGeneratedExceptionFilter")
					{
						continue;
					}
				}
			}
			if (!(stacktraceEntry.ModuleInfo?.Id == "Bannerlord.MBOptionScreen") || !(stacktraceEntry.Method.Name == "ExecuteCommandPatch"))
			{
				yield return stacktraceEntry with
				{
					PatchMethods = FilterPatches(stacktraceEntry.PatchMethods).ToArray()
				};
			}
		}
	}

	private IEnumerable<MethodEntry> FilterPatches(ICollection<MethodEntry> patches)
	{
		foreach (MethodEntry patch in patches)
		{
			if (patch.Method == _bewFinalizer)
			{
				continue;
			}
			MethodBase method = patch.Method;
			if ((object)method != null && method.Name == "Finalizer")
			{
				Type declaringType = method.DeclaringType;
				if ((object)declaringType != null && declaringType.Name == "AutoGeneratedExceptionFilter")
				{
					continue;
				}
			}
			if (!(patch.Method.DeclaringType == typeof(MBSubModuleBaseWrapper)) && !(patch.Method.DeclaringType == typeof(MBSubModuleBaseListWrapper)) && !(patch.Method.DeclaringType == typeof(MBSubModuleBasePatch)) && !(patch.LoaderPluginInfo?.Id == "BLSE.ExceptionInterceptor") && (!(patch.ModuleInfo?.Id == "Bannerlord.Harmony") || !(patch.Method.DeclaringType?.FullName == "Bannerlord.Harmony.SubModule") || !(patch.Method.Name == "OnBeforeInitialModuleScreenSetAsRootPostfix")))
			{
				yield return patch;
			}
		}
	}
}
