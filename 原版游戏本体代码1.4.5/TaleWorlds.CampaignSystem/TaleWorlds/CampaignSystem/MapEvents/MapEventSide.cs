	private void MakeReady(bool includeHumanPlayers, int sizeOfSide, FlattenedTroopRoster priorTroops = null)
	{
		bool flag = includeHumanPlayers;
		if (_readyTroopsPriorityList == null || _allocatedTroops == null)
		{
			_readyTroopsPriorityList = new List<(FlattenedTroopRosterElement, MapEventParty, float)>();
			_allocatedTroops = new Dictionary<UniqueTroopDescriptor, MapEventParty>();
		}
		else
		{
			_readyTroopsPriorityList.Clear();
			_allocatedTroops.Clear();
		}
		int healthyTroopCountAtMapEventStart = HealthyTroopCountAtMapEventStart;
		int num = 0;
		for (int i = 0; i < _battleParties.Count; i++)
		{
			MapEventParty mapEventParty = _battleParties[i];
			int a = TaleWorlds.Library.MathF.Round((float)mapEventParty.HealthyManCountAtStart / (float)healthyTroopCountAtMapEventStart * (float)sizeOfSide);
			int num2;
			if (i < _battleParties.Count - 1)
			{
				num2 = TaleWorlds.Library.MathF.Min(a, sizeOfSide - num);
				num += num2;
			}
			else
			{
				num2 = TaleWorlds.Library.MathF.Max(0, sizeOfSide - num);
			}
			MakeReadyParty(mapEventParty, priorTroops, includeHumanPlayers, num2);
		}
		if (flag)
		{
			_readyTroopsPriorityList.Sort(((FlattenedTroopRosterElement, MapEventParty, float) tuple, (FlattenedTroopRosterElement, MapEventParty, float) b) => b.Item3.CompareTo(tuple.Item3));
		}
		_requiresTroopCacheUpdate = true;
	}

	private void MakeReadyParty(MapEventParty battleParty, FlattenedTroopRoster priorityTroops, bool includePlayers, int sizeOfParty)
	{
		battleParty.SetParticipatingTroopCount(sizeOfParty);
		if (!_troopAllocationsLocked)
		{
			battleParty.Update();
		}
		bool forcePriorityTroops = priorityTroops != null && _mapEvent.PlayerSide == MissionSide && (_mapEvent.IsHideoutBattle || (_mapEvent.IsSiegeAssault && PlayerSiege.BesiegedSettlement != null && PlayerSiege.BesiegedSettlement.CurrentSiegeState == Settlement.SiegeState.InTheLordsHall));
		Campaign.Current.Models.TroopSupplierProbabilityModel.EnqueueTroopSpawnProbabilitiesAccordingToUnitSpawnPrioritization(battleParty, priorityTroops, includePlayers, sizeOfParty, forcePriorityTroops, _readyTroopsPriorityList);
	}

	private void CheckReadyTroopsTemporaryCache()
	{
		if (_readyTroopsTemporaryCache == null)
		{
			_readyTroopsTemporaryCache = new Dictionary<UniqueTroopDescriptor, MapEventParty>();
		}
		if (!_requiresTroopCacheUpdate)
		{
			return;
		}
		_readyTroopsTemporaryCache.Clear();
		foreach (var readyTroopsPriority in _readyTroopsPriorityList)
		{
			Dictionary<UniqueTroopDescriptor, MapEventParty> readyTroopsTemporaryCache = _readyTroopsTemporaryCache;
			var (flattenedTroopRosterElement, _, _) = readyTroopsPriority;
			readyTroopsTemporaryCache.Add(flattenedTroopRosterElement.Descriptor, readyTroopsPriority.Item2);
		}
		_requiresTroopCacheUpdate = false;
	}

	public void MakeReadyForSimulation(FlattenedTroopRoster priorTroops, int sizeOfSide)
	{
		if (_troopAllocationsLocked)
		{
			return;
		}
		MakeReady(includeHumanPlayers: false, sizeOfSide, priorTroops);
		AllocateTroops(ref _simulationTroopList, sizeOfSide);
		AllocateShips();
		AllocateSiegeEngines();
		if (!_battleParties.AnyQ((MapEventParty p) => p.HasTroopLimit))
		{
			return;
		}
		_troopAllocationsLocked = true;
		foreach (MapEventParty battleParty in _battleParties)
		{
			battleParty.TrimRosterToAllocatedTroops(_allocatedTroops);
		}
	}

	public void MakeReadyForMission(FlattenedTroopRoster priorTroops)
	{
		InvalidateSimulationSetup();
		int sizeOfSide = priorTroops?.Count() ?? TroopCount;
		MakeReady(includeHumanPlayers: true, sizeOfSide, priorTroops);
	}

	public void EndSimulation()
