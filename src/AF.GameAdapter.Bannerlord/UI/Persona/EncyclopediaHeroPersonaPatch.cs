	}

	private static bool IsCourierBlockedByDirectContact(Hero hero, bool forceMissionRefresh)
	{
		if (hero == null)
		{
			return false;
		}
		try
		{
			ConversationManager conversationManager = Campaign.Current?.ConversationManager;
			if (conversationManager?.IsConversationInProgress == true
				&& (ReferenceEquals(conversationManager.OneToOneConversationCharacter?.HeroObject, hero)
					|| ReferenceEquals(Hero.OneToOneConversationHero, hero)))
			{
				return true;
			}
		}
		catch
		{
		}
		if (IsHeroInSameSettlementAsPlayer(hero))
		{
			return true;
		}

		Mission mission;
		try
		{
			mission = Mission.Current;
		}
		catch
		{
			mission = null;
		}
		if (mission == null)
		{
			_cachedCourierPresenceHero = null;
			_cachedCourierPresenceMission = null;
			_cachedCourierHeroInMission = false;
			_cachedCourierPresenceExpiresAt = 0L;
			return false;
		}

		long now = Stopwatch.GetTimestamp();
		if (!forceMissionRefresh
			&& ReferenceEquals(_cachedCourierPresenceHero, hero)
			&& ReferenceEquals(_cachedCourierPresenceMission, mission)
			&& now < _cachedCourierPresenceExpiresAt)
		{
			return _cachedCourierHeroInMission;
		}

		bool heroInMission = IsHeroPresentInMission(mission, hero);
		_cachedCourierPresenceHero = hero;
		_cachedCourierPresenceMission = mission;
		_cachedCourierHeroInMission = heroInMission;
		_cachedCourierPresenceExpiresAt = now + CourierMissionPresenceCacheTicks;
		return heroInMission;
	}

	private static bool IsHeroInSameSettlementAsPlayer(Hero hero)
	{
		try
		{
			Settlement playerSettlement = Settlement.CurrentSettlement
				?? Hero.MainHero?.CurrentSettlement
				?? MobileParty.MainParty?.CurrentSettlement;
			return playerSettlement != null && ReferenceEquals(hero?.CurrentSettlement, playerSettlement);
		}
		catch
		{
			return false;
		}
	}

	private static bool IsHeroPresentInMission(Mission mission, Hero hero)
	{
		try
		{
			var agents = mission?.Agents;
			if (hero == null || agents == null)
			{
				return false;
			}
			foreach (Agent agent in agents)
			{
				if (agent?.Character is CharacterObject characterObject
					&& ReferenceEquals(characterObject.HeroObject, hero))
				{
					return true;
				}
			}
		}
		catch
		{
		}
