			return null;
		}
		Widget reflected = AccessTools.Field(root.GetType(), "_widget_0_0_1")?.GetValue(root) as Widget;
		if (reflected != null)
		{
			return reflected;
		}
		Widget widget = root as Widget;
		return widget?.FindChild("RightSideScrollablePanel", includeAllChildren: true);
	}
