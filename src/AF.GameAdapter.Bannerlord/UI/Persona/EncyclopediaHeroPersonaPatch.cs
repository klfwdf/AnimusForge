	private static void ProcessPendingRefreshes()
	{
		if (System.Threading.Volatile.Read(ref _hasPendingRefreshes) == 0)
		{
			return;
		}
		List<PendingRefresh> pending = null;
		lock (SyncRoot)
		{
			if (PendingRefreshes.Count <= 0)
			{
				System.Threading.Volatile.Write(ref _hasPendingRefreshes, 0);
				return;
			}
			pending = new List<PendingRefresh>(PendingRefreshes);
			PendingRefreshes.Clear();
			System.Threading.Volatile.Write(ref _hasPendingRefreshes, 0);
		}
		foreach (PendingRefresh pendingRefresh in pending)
		{
			try
			{
				string heroId = (pendingRefresh?.HeroId ?? "").Trim();
				RefreshLiveGeneratedRootsForHero(heroId);
			}
			catch (Exception ex)
			{
				Logger.Log("EncyclopediaPersona", "[WARN] Failed to refresh hero encyclopedia persona text: " + ex.Message);
			}
		}
	}

	private static void UpdateLiveGeneratedRoots()
	{
		if (System.Threading.Volatile.Read(ref _hasLiveGeneratedRoots) == 0)
		{
			return;
		}
		List<object> roots;
		lock (SyncRoot)
		{
			if (LiveGeneratedRoots.Count == 0)
			{
				System.Threading.Volatile.Write(ref _hasLiveGeneratedRoots, 0);
				return;
			}
			roots = new List<object>(LiveGeneratedRoots.Count);
			for (int i = LiveGeneratedRoots.Count - 1; i >= 0; i--)
			{
				object target = LiveGeneratedRoots[i]?.Target;
				if (target == null || !IsRootUsableForLiveUpdate(target))
				{
					LiveGeneratedRoots.RemoveAt(i);
				}
				else
				{
					roots.Add(target);
				}
			}
			if (LiveGeneratedRoots.Count == 0)
			{
				System.Threading.Volatile.Write(ref _hasLiveGeneratedRoots, 0);
			}
		}
		foreach (object root in roots)
		{
			if (!TryUpdateGeneratedRoot(root, updateText: true))
			{
				RemoveTrackedRoot(root);
			}
		}
	}

	private static void RefreshLiveGeneratedRootsForHero(string heroId)
	{
		List<object> roots = new List<object>();
		lock (SyncRoot)
		{
			for (int i = LiveGeneratedRoots.Count - 1; i >= 0; i--)
			{
				object target = LiveGeneratedRoots[i]?.Target;
				if (target == null || !IsRootUsableForLiveUpdate(target))
				{
					LiveGeneratedRoots.RemoveAt(i);
				}
				else
				{
					roots.Add(target);
				}
			}
		}
		foreach (object root in roots)
		{
			try
			{
				EncyclopediaHeroPageVM vm = GetDataSource(root);
				Hero hero = ResolveHero(vm);
				if (string.IsNullOrWhiteSpace(heroId) || string.Equals(hero?.StringId ?? "", heroId, StringComparison.OrdinalIgnoreCase))
				{
					if (!TryUpdateGeneratedRoot(root, updateText: true))
					{
						RemoveTrackedRoot(root);
					}
				}
			}
			catch (Exception ex)
			{
				LogLiveRootUpdateFailure(ex);
				RemoveTrackedRoot(root);
			}
		}
	}

	private static void TrackGeneratedRoot(object root, EncyclopediaHeroPageVM vm = null)
	{
		if (root == null)
		{
			return;
		}
		if (vm != null)
		{
			RootDataSources.Remove(root);
			RootDataSources.Add(root, vm);
		}
		lock (SyncRoot)
		{
			foreach (WeakReference weakReference in LiveGeneratedRoots)
			{
				if (ReferenceEquals(weakReference?.Target, root))
				{
					return;
				}
			}
			LiveGeneratedRoots.Add(new WeakReference(root));
			System.Threading.Volatile.Write(ref _hasLiveGeneratedRoots, 1);
		}
	}

	private static bool TryUpdateGeneratedRoot(object root, bool updateText)
	{
		try
		{
			return UpdateGeneratedRoot(root, updateText);
		}
		catch (Exception ex)
		{
			LogLiveRootUpdateFailure(ex);
			return false;
		}
	}

	private static bool UpdateGeneratedRoot(object root, bool updateText)
	{
		if (root == null)
		{
			return true;
		}
		EncyclopediaHeroPageVM vm = GetDataSource(root);
		Hero hero = ResolveHero(vm);
		if (updateText)
		{
			ApplyPersonaText(vm, hero);
		}
		ButtonWidget button = GetEditButton(root);
		bool stateWriteSucceeded = true;
		if (button != null)
		{
			bool shouldShow = ShouldShowEditButton(hero, vm);
			stateWriteSucceeded &= SetWidgetVisibleIfChanged(button, shouldShow);
			LogFirstButtonState(hero, vm, shouldShow);
		}
		ButtonWidget courierButton = GetCourierButton(root);
		if (courierButton != null)
		{
			bool shouldShowCourier = ShouldShowCourierButton(hero, vm);
			bool shouldEnableCourier = shouldShowCourier
				&& !CourierDeliveryBehavior.HasActiveCourierForHeroForExternal(hero)
				&& !IsCourierBlockedByDirectContact(hero, forceMissionRefresh: false);
			stateWriteSucceeded &= SetWidgetVisibleIfChanged(courierButton, shouldShowCourier);
			stateWriteSucceeded &= SetWidgetEnabledIfChanged(courierButton, shouldEnableCourier);
		}
		ButtonWidget rerollButton = GetRerollButton(root);
		if (rerollButton != null)
		{
			bool shouldShowReroll = ShouldShowRerollButton(hero, vm);
			bool generationActive = MyBehavior.TryGetNpcPersonaGenerationRuntimeStateForExternal(hero, out var active, out var _) && active;
			stateWriteSucceeded &= SetWidgetVisibleIfChanged(rerollButton, shouldShowReroll);
			stateWriteSucceeded &= SetWidgetEnabledIfChanged(rerollButton, shouldShowReroll && !generationActive);
		}
		return stateWriteSucceeded;
	}

	private static bool IsRootUsableForLiveUpdate(object root)
	{
		Widget widget = root as Widget;
		if (widget == null)
		{
			return false;
		}
		if (!IsWidgetSafeForStateWrite(widget))
		{
			LogStaleRootSkip(widget);
			return false;
		}
		return true;
	}

	private static bool IsWidgetSafeForStateWrite(Widget widget)
	{
		if (widget == null)
		{
			return false;
		}
		try
		{
			UIContext context = widget.Context;
			EventManager eventManager = context?.EventManager;
			if (eventManager == null || !widget.ConnectedToRoot || !IsAnchoredToEventRoot(widget, eventManager))
			{
				return false;
			}
			return HasUsableEventContainers(eventManager);
		}
		catch
		{
			return false;
		}
	}

	private static bool IsAnchoredToEventRoot(Widget widget, EventManager eventManager)
	{
		Widget root = eventManager?.Root;
		if (widget == null || root == null)
		{
			return false;
		}
		int depth = 0;
		for (Widget current = widget; current != null && depth < 512; current = current.ParentWidget)
		{
			if (ReferenceEquals(current, root))
			{
				return true;
			}
			depth++;
		}
		return false;
	}

	private static bool HasUsableEventContainers(EventManager eventManager)
	{
		if (eventManager == null || EventManagerWidgetContainersField == null)
		{
			return false;
		}
		object containers = EventManagerWidgetContainersField.GetValue(eventManager);
		if (containers == null)
		{
			return false;
		}
		if (containers is Array containerArray)
		{
			return containerArray.Length > UpdateBrushesContainerIndex && containerArray.GetValue(UpdateBrushesContainerIndex) != null;
		}
		if (containers is IDictionary containerDictionary)
		{
			foreach (DictionaryEntry entry in containerDictionary)
			{
				if (entry.Value != null && string.Equals(entry.Key?.ToString(), "UpdateBrushes", StringComparison.Ordinal))
				{
					return true;
				}
			}
			return false;
		}
		return true;
	}

	private static bool SetWidgetVisibleIfChanged(Widget widget, bool visible)
	{
		try
		{
			if (widget == null || widget.IsVisible == visible)
			{
				return true;
			}
			if (!IsWidgetSafeForStateWrite(widget))
			{
				LogUnsafeStateWriteSkip();
				return false;
			}
			widget.IsVisible = visible;
			return true;
		}
		catch (Exception ex)
		{
			LogLiveRootUpdateFailure(ex);
			return false;
		}
	}

	private static bool SetWidgetEnabledIfChanged(Widget widget, bool enabled)
	{
		try
		{
			if (widget == null || widget.IsEnabled == enabled)
			{
				return true;
			}
			if (!IsWidgetSafeForStateWrite(widget))
			{
				LogUnsafeStateWriteSkip();
				return false;
			}
			widget.IsEnabled = enabled;
			return true;
		}
		catch (Exception ex)
		{
			LogLiveRootUpdateFailure(ex);
			return false;
		}
	}

