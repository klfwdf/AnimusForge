	internal void ProcessPendingWeeklyReportManualRetryResult()
	{
		if (!PendingManualRetryResult)
		{
			return;
		}
		bool pendingWeeklyReportManualRetrySucceeded = PendingManualRetrySucceeded;
		string text = (PendingManualRetryMessage ?? "").Trim();
		WeeklyReportRetryContext weeklyReportRetryContext = PendingManualRetryContext;
		PendingManualRetryResult = false;
		PendingManualRetrySucceeded = false;
		PendingManualRetryMessage = "";
		PendingManualRetryContext = null;
		ManualRetryInProgress = false;
		InformationManager.HideInquiry();
		if (pendingWeeklyReportManualRetrySucceeded)
		{
			RetryContext = null;
			UiStage = WeeklyReportUiStage.None;
			if (!string.IsNullOrWhiteSpace(text))
			{
				InformationManager.DisplayMessage(new InformationMessage(text));
			}
			return;
		}
		if (weeklyReportRetryContext != null)
		{
			RetryContext = weeklyReportRetryContext;
		}
		UiStage = WeeklyReportUiStage.None;
		if (!string.IsNullOrWhiteSpace(text))
		{
			InformationManager.DisplayMessage(new InformationMessage(text));
		}
		QueueWeeklyReportFailurePopup(RetryContext, showImmediate: true);
	}


	internal void BeginRetryBlockedWeeklyReports()
	{
		if (RetryContext == null || ManualRetryInProgress)
		{
			return;
		}
		ManualRetryInProgress = true;
		int num = ++ManualRetryVersion;
		UiStage = WeeklyReportUiStage.RetryProgress;
		ShowWeeklyReportRetryProgressPopup();
		_ = RetryBlockedWeeklyReportsAsync(RetryContext, num);
	}


	internal void BeginFreshWeeklyReportRetry(WeeklyReportRetryContext staleContext)
	{
		if (!_port.IsMainThreadAndHostCurrent() || !ReferenceEquals(RetryContext, staleContext) || ManualRetryInProgress)
		{
			return;
		}
		try
		{
			List<WeeklyEventMaterialPreviewGroup> freshGroups = SelectFreshWeeklyReportRetryGroups(_port.CollectFreshMaterials(staleContext.StartDay, staleContext.EndDay), staleContext.Groups);
			if (freshGroups == null || freshGroups.Count == 0)
			{
				InformationManager.DisplayMessage(new InformationMessage("当前已无法找到全部失败的周报分组，未发送新请求；请保存退出后检查本周素材。"));
				QueueWeeklyReportFailurePopup(staleContext, showImmediate: true);
				return;
			}
			freshGroups = _port.OrderWeeklyReportGenerationGroups(freshGroups);
			WeeklyReportRetryContext freshContext = _port.CreateFreshRetryContext(staleContext, freshGroups);
			RetryContext = freshContext;
			BeginRetryBlockedWeeklyReports();
		}
		catch (Exception ex)
		{
			Logger.Log("EventWeeklyReport", "[ERROR] refresh changed weekly report materials failed: " + ex);
			InformationManager.DisplayMessage(new InformationMessage("重新采集周报素材失败，未发送新请求。"));
			QueueWeeklyReportFailurePopup(staleContext, showImmediate: true);
		}
	}


	internal List<WeeklyEventMaterialPreviewGroup> SelectFreshWeeklyReportRetryGroups(List<WeeklyEventMaterialPreviewGroup> freshGroups, List<WeeklyEventMaterialPreviewGroup> failedGroups)
	{
		HashSet<string> requiredIds = new HashSet<string>((failedGroups ?? new List<WeeklyEventMaterialPreviewGroup>()).Select(group => _port.BuildWeeklyReportGroupReportId(group)).Where((string id) => !string.IsNullOrWhiteSpace(id)), StringComparer.OrdinalIgnoreCase);
		if (requiredIds.Count == 0)
		{
			return null;
		}
		List<WeeklyEventMaterialPreviewGroup> selected = (freshGroups ?? new List<WeeklyEventMaterialPreviewGroup>()).Where((WeeklyEventMaterialPreviewGroup group) => group != null && requiredIds.Contains(_port.BuildWeeklyReportGroupReportId(group))).ToList();
		return _port.BuildGroupMap(selected).Count == requiredIds.Count ? selected : null;
	}


	internal async Task RetryBlockedWeeklyReportsAsync(WeeklyReportRetryContext context, int retryVersion)
	{
		long generation = _port.CaptureGeneration();
		WeeklyReportGenerationResult weeklyReportGenerationResult = null;
		try
		{
			weeklyReportGenerationResult = await _port.GenerateRetry(context);
			if (retryVersion != ManualRetryVersion || !_port.IsCurrent(generation) || !ReferenceEquals(RetryContext, context))
			{
				return;
			}
			PendingManualRetrySucceeded = weeklyReportGenerationResult != null && weeklyReportGenerationResult.Completed && !weeklyReportGenerationResult.BlockedByFatalFailure;
			if (PendingManualRetrySucceeded)
			{
				if (context.IsAutoGeneration)
				{
					_port.MarkAutoGeneratedWeek(context.WeekIndex);
				}
				PendingManualRetryMessage = "周事件补跑成功，已解除暂停。";
				PendingManualRetryContext = null;
			}
			else
			{
				if (weeklyReportGenerationResult?.BlockedByChangedRecord == true)
				{
					context.RequiresFreshMaterials = true;
					context.FailedReason = "周报目标在失败后已变更，旧素材不能重试。";
				}
				PendingManualRetryMessage = weeklyReportGenerationResult?.BlockedByChangedRecord == true
					? "周报目标已被编辑或由其他请求完成，旧素材不能重试；请重新收集本周素材并生成。"
					: "周事件补跑仍未成功，请检查 API / 模型配置后再试。";
				PendingManualRetryContext = (weeklyReportGenerationResult?.RetryContext ?? context);
			}
		}
		catch (Exception ex)
		{
			if (retryVersion != ManualRetryVersion || !_port.IsCurrent(generation) || !ReferenceEquals(RetryContext, context))
			{
				return;
			}
			Logger.Log("EventWeeklyReport", "[ERROR] RetryBlockedWeeklyReportsAsync failed: " + ex);
			PendingManualRetrySucceeded = false;
			PendingManualRetryMessage = "周事件补跑异常失败：" + ex.Message;
			PendingManualRetryContext = context;
		}
		finally
		{
			if (retryVersion == ManualRetryVersion && _port.IsCurrent(generation) && ReferenceEquals(RetryContext, context))
			{
				PendingManualRetryResult = true;
			}
		}
	}

