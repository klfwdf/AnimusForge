	internal void ProcessWeeklyReportUiResume()
	{
		if (ReopenAfterApiConfig && RetryContext != null && !PendingManualRetryResult)
		{
			if (!InformationManager.IsAnyInquiryActive() && DateTime.UtcNow.Ticks >= ReopenAfterApiConfigUtcTicks)
			{
				ReopenAfterApiConfig = false;
				ShowWeeklyReportFailurePopup(ignoreDelay: true);
			}
		}
		if (RetryContext == null || PendingManualRetryResult)
		{
			return;
		}
		if (UiStage != WeeklyReportUiStage.Failure && UiStage != WeeklyReportUiStage.RetryProgress)
		{
			return;
		}
		if (InformationManager.IsAnyInquiryActive())
		{
			return;
		}
		if (DateTime.UtcNow.Ticks < UiResumeAfterUtcTicks)
		{
			return;
		}
		if (UiStage == WeeklyReportUiStage.RetryProgress && ManualRetryInProgress)
		{
			ShowWeeklyReportRetryProgressPopup();
			return;
		}
		if (UiStage == WeeklyReportUiStage.Failure)
		{
			ShowWeeklyReportFailurePopup(ignoreDelay: true);
		}
	}


