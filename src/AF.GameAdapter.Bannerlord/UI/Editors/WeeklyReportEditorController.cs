	}


	internal void ShowWeeklyReportFailurePopup(bool ignoreDelay = false)
	{
        long generation = _port.CaptureGeneration();
        var expectedContext = RetryContext;
        long ticket = ++_failureUiTicket;
        bool consumed = false;
        bool Take() { if (consumed || ticket != _failureUiTicket || !_port.IsCurrent(generation) || !ReferenceEquals(RetryContext, expectedContext)) return false; consumed = true; return true; }
		if (RetryContext == null || ManualRetryInProgress)
		{
			return;
		}
		long ticks = DateTime.UtcNow.Ticks;
		if (!ignoreDelay && ticks < UiResumeAfterUtcTicks)
		{
			return;
		}
		UiStage = WeeklyReportUiStage.Failure;
		UiResumeAfterUtcTicks = ticks + TimeSpan.FromMilliseconds(150.0).Ticks;
		WeeklyReportRetryContext weeklyReportRetryContext = RetryContext;
        string text = FormatNewsDate(weeklyReportRetryContext.EndDay) + WeeklyReportUiText.Get("AF_UI_Weekly_Editor_094","Automatic weekly report");
