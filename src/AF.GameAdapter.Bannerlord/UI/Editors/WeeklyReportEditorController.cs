		{
			text = FormatNewsDate(weeklyReportRetryContext.EndDay) + WeeklyReportUiText.Get("AF_UI_Weekly_Editor_095","Weekly report");
		}
		if (weeklyReportRetryContext.RequiresFreshMaterials)
