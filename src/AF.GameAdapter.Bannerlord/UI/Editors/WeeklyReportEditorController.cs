	internal List<WeeklyReportBrowserCountryData> GetTerminalWeeklyReportBrowserCountries()
	{
		try
		{
			_port.EnsureWeekZeroOpeningSummaryEvents();
		}
		catch
		{
		}
        var bulletinAssociations = _port.BulletinKingdomAssociations?.Invoke();
		List<EventRecordEntry> list = WeeklyReportArchivePolicy.BuildArchiveSnapshot(_port.SanitizeEventRecordEntries(_port.EventRecords()), bulletinAssociations);
		List<WeeklyReportBrowserCountryData> list2 = new List<WeeklyReportBrowserCountryData>();
		HashSet<string> hashSet = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
		WeeklyReportBrowserCountryData item = BuildWeeklyReportBrowserCountryData("world", "", "全部档案", isWorld: true, list, bulletinAssociations);
		list2.Add(item);
		hashSet.Add("world:");
		foreach (Kingdom item2 in _port.GetDevEditableKingdoms().OrderBy((Kingdom x) => _port.ResolveKingdomDisplay(x?.StringId), StringComparer.OrdinalIgnoreCase))
		{
			string text = (item2?.StringId ?? "").Trim();
			if (!string.IsNullOrWhiteSpace(text) && hashSet.Add("kingdom:" + text))
			{
				list2.Add(BuildWeeklyReportBrowserCountryData("kingdom", text, _port.ResolveKingdomDisplay(text), isWorld: false, list, bulletinAssociations));
			}
		}
		foreach (string item3 in list.Where(x => x != null).SelectMany(x =>
            (string.Equals((x.EventKind ?? "").Trim(), "kingdom", StringComparison.OrdinalIgnoreCase)
                && !string.IsNullOrWhiteSpace(x.ScopeKingdomId) ? new[] { x.ScopeKingdomId.Trim() } : Array.Empty<string>())
            .Concat(WeeklyReportArchivePolicy.RelatedKingdomIds(x, bulletinAssociations)))
            .Where(id => !string.IsNullOrWhiteSpace(id)).Distinct(StringComparer.OrdinalIgnoreCase).OrderBy((string x) => _port.ResolveKingdomDisplay(x), StringComparer.OrdinalIgnoreCase))
		{
			if (hashSet.Add("kingdom:" + item3))
			{
				list2.Add(BuildWeeklyReportBrowserCountryData("kingdom", item3, item3 == WeeklyReportArchivePolicy.OtherKingdomId ? "其他近况" : _port.ResolveKingdomDisplay(item3), isWorld: false, list, bulletinAssociations));
			}
		}
		return list2;
	}

    internal bool OpenArchivedReport(string eventId)
    {
        var entry = WeeklyReportArchivePolicy.BuildArchiveSnapshot(_port.SanitizeEventRecordEntries(_port.EventRecords()), _port.BulletinKingdomAssociations?.Invoke())
            .FirstOrDefault(e => string.Equals(e.EventId, eventId, StringComparison.OrdinalIgnoreCase));
        if (entry == null) return false;
        bool bulletin = WeeklyReportArchivePolicy.IsBulletin(entry.EventId);
        if (bulletin)
        {
            WorldBulletinPanelData data = null;
            try { data = _port.BuildBulletinPanel(entry, entry.EventId); }
            catch (Exception ex) { Logger.Log("WorldBulletinPanel", "[WARN] archive panel data build failed, using legacy popup: " + ex.Message); }
            if (data != null && DevWeeklyReportPopup.ShowWorldBulletin(data)) return true;
        }
        return DevWeeklyReportPopup.Show(entry.Title, entry.CreatedDate, WeeklyReportArchivePolicy.BodyWithRegionalNews(entry),
            closeText: "关闭", useChronicleColumns: !bulletin && !string.IsNullOrWhiteSpace(entry.Summary));
    }

	internal void OpenDevWeeklyEventMaterialPreviewGroupDetail(WeeklyEventMaterialPreviewGroup group, int page)
	{
		long editorGeneration = _port.CaptureGeneration();
		if (!_port.IsCurrent(editorGeneration)) return;
		MaterialSelection = group;
		if (group == null)
		{
			OpenDevWeeklyEventMaterialPreviewMenu();
			return;
		}
		List<EventMaterialReference> list = _port.OrderWeeklyPreviewMaterials(group.Materials).ToList();
		if (page < 0)
		{
			page = 0;
		}
		const int pageSize = 16;
		int num = Math.Max(1, (int)Math.Ceiling((double)Math.Max(1, list.Count) / (double)pageSize));
		if (page >= num)
		{
			page = num - 1;
		}
		MaterialPage = page;
		List<InquiryElement> list2 = new List<InquiryElement>();
		list2.Add(new InquiryElement("back", "返回分组列表", null));
		if (page > 0)
		{
			list2.Add(new InquiryElement("prev_page", "上一页", null));
		}
		if (page + 1 < num)
		{
			list2.Add(new InquiryElement("next_page", "下一页", null));
		}
		list2.Add(new InquiryElement("__sep__", "----------------", null));
		foreach (EventMaterialReference item in list.Skip(page * pageSize).Take(pageSize))
		{
			list2.Add(new InquiryElement(item, BuildWeeklyPreviewMaterialLabel(item), null));
		}
		MultiSelectionInquiryData data = new MultiSelectionInquiryData(group.Title ?? "素材预览", BuildWeeklyPreviewGroupDetailText(group, page, num), list2, isExitShown: true, 0, 1, "查看素材", "返回", delegate(List<InquiryElement> selected)
		{
			if (!_port.IsCurrent(editorGeneration)) return;
			if (selected == null || selected.Count == 0)
			{
				OpenDevWeeklyEventMaterialPreviewMenu();
			}
			else if (selected[0].Identifier is string text)
			{
				switch (text)
				{
				case "back":
					OpenDevWeeklyEventMaterialPreviewMenu();
					break;
				case "prev_page":
					OpenDevWeeklyEventMaterialPreviewGroupDetail(group, page - 1);
					break;
				case "next_page":
					OpenDevWeeklyEventMaterialPreviewGroupDetail(group, page + 1);
					break;
				default:
					OpenDevWeeklyEventMaterialPreviewGroupDetail(group, page);
					break;
				}
			}
			else if (selected[0].Identifier is EventMaterialReference eventMaterialReference)
			{
				OpenDevWeeklyPreviewMaterialDetail(group, eventMaterialReference, page);
			}
			else
			{
				OpenDevWeeklyEventMaterialPreviewGroupDetail(group, page);
			}
		}, delegate
		{
			if (!_port.IsCurrent(editorGeneration)) return;
			OpenDevWeeklyEventMaterialPreviewMenu();
		});
		MBInformationManager.ShowMultiSelectionInquiry(data);
	}

