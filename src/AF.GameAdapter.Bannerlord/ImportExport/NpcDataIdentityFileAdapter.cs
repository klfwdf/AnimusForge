using System;
using System.IO;
using System.Collections.Generic;
using TaleWorlds.CampaignSystem;

namespace AnimusForge;

// File lookup is a manual cold path; live Hero identity is read on the campaign thread.
internal static class NpcDataIdentityFileAdapter
{
	internal static string FindNpcJsonByHeroId(string dir, string heroId)
	{
		try
		{
			if (string.IsNullOrEmpty(dir) || !Directory.Exists(dir))
			{
				return null;
			}
			string text = (heroId ?? "").Trim();
			if (string.IsNullOrEmpty(text))
			{
				return null;
			}
			string result = null;
			string nameMatchedResult = null;
			DateTime dateTime = DateTime.MinValue;
			DateTime nameMatchedDateTime = DateTime.MinValue;
			Hero targetHero = MemoryEntityIdentityBannerlordAdapter.ResolveHeroByIdForNpcData(text);
			string[] files = Directory.GetFiles(dir, "*.json");
			string[] array = files;
			foreach (string text2 in array)
			{
				if (!NpcDataFileName.TryParseParts(text2, out var text3, out var fileDisplayName))
				{
					continue;
				}
				if (!(text3 != text))
				{
					if (targetHero != null && !NpcDataFileName.IsDisplayNameCompatible(fileDisplayName, targetHero?.Name?.ToString(), targetHero != null, NpcDataFileName.IsAutoGeneratedHeroId(text)))
					{
						continue;
					}
					DateTime lastWriteTimeUtc = File.GetLastWriteTimeUtc(text2);
					if (lastWriteTimeUtc > dateTime)
					{
						result = text2;
						dateTime = lastWriteTimeUtc;
					}
				}
				else if (targetHero != null && NpcDataFileName.IsDisplayNameSpecified(fileDisplayName) && NpcDataFileName.IsDisplayNameCompatible(fileDisplayName, targetHero?.Name?.ToString(), targetHero != null, strictWhenNameMissing: true))
				{
					DateTime lastWriteTimeUtc2 = File.GetLastWriteTimeUtc(text2);
					if (lastWriteTimeUtc2 > nameMatchedDateTime)
					{
						nameMatchedResult = text2;
						nameMatchedDateTime = lastWriteTimeUtc2;
					}
				}
			}
			return result ?? nameMatchedResult;
		}
		catch
		{
			return null;
		}
	}

	internal static string ResolveHeroNameForNpcDataFile(string heroId)
	{
		string id = (heroId ?? "").Trim();
		if (string.IsNullOrEmpty(id))
		{
			return "";
		}
		try
		{
			return Hero.FindFirst((Hero x) => x != null && x.StringId == id)?.Name?.ToString() ?? "";
		}
		catch
		{
			return "";
		}
	}

	internal static bool TryResolveNpcDataFileHeroIdForImport(string filePath, out string resolvedHeroId, out string warning)
  => ResolveImportIdentity(filePath,out resolvedHeroId,out warning,
   MemoryEntityIdentityBannerlordAdapter.ResolveHeroByIdForNpcData,
   MemoryEntityIdentityBannerlordAdapter.ResolveUniqueHeroByNpcFileDisplayName);

	private static bool ResolveImportIdentity(string filePath, out string resolvedHeroId, out string warning, Func<string,Hero> byId, Func<string,Hero> byName)
	{
		resolvedHeroId = "";
		warning = "";
		if (!NpcDataFileName.TryParseParts(filePath, out var parsedHeroId, out var fileDisplayName))
		{
			warning = "文件名缺少 heroId__名字 格式。";
			return false;
		}
		Hero currentHeroById = byId(parsedHeroId);
		bool autoGeneratedId = NpcDataFileName.IsAutoGeneratedHeroId(parsedHeroId);
		if (currentHeroById != null && NpcDataFileName.IsDisplayNameCompatible(fileDisplayName, currentHeroById?.Name?.ToString(), currentHeroById != null, autoGeneratedId))
		{
			resolvedHeroId = (currentHeroById.StringId ?? parsedHeroId).Trim();
			return !string.IsNullOrWhiteSpace(resolvedHeroId);
		}
		Hero currentHeroByName = byName(fileDisplayName);
		if (currentHeroByName != null)
		{
			resolvedHeroId = (currentHeroByName.StringId ?? "").Trim();
			if (!string.Equals(resolvedHeroId, parsedHeroId, StringComparison.OrdinalIgnoreCase))
			{
				Logger.Log("NpcPersona", "[INFO] Remapped NPC data file by unique name: file=" + Path.GetFileName(filePath) + " oldId=" + parsedHeroId + " newId=" + resolvedHeroId + " name=" + (currentHeroByName.Name?.ToString() ?? ""));
			}
			return !string.IsNullOrWhiteSpace(resolvedHeroId);
		}
		if (currentHeroById != null)
		{
			warning = "文件名人物名“" + NpcDataFileName.NormalizeDisplayName(fileDisplayName) + "”与当前同 ID 人物“" + (currentHeroById.Name?.ToString() ?? "") + "”不一致。";
			return false;
		}
		if (autoGeneratedId)
		{
			warning = "自动编号 " + parsedHeroId + " 在当前存档中不可可靠匹配，且文件名人物名不能唯一匹配。";
			return false;
		}
		resolvedHeroId = parsedHeroId;
		return true;
	}

 // This scope belongs to one synchronous preparation/export only. Never stored on a controller.
 internal sealed class LookupScope
 {
  private readonly Dictionary<string,Hero> _ids=new Dictionary<string,Hero>(StringComparer.Ordinal);
  private readonly Dictionary<string,Hero> _names=new Dictionary<string,Hero>(StringComparer.OrdinalIgnoreCase);
  private readonly Dictionary<string,string> _fileNames=new Dictionary<string,string>(StringComparer.Ordinal);
  internal int IdentityFiles, IdLookups, UniqueNameLookups, FilenameLookups;
  private Hero ById(string id)
  {
   string key=(id??"").Trim();
   if (!_ids.TryGetValue(key,out var hero))
   { hero=MemoryEntityIdentityBannerlordAdapter.ResolveHeroByIdForNpcData(key);_ids[key]=hero;IdLookups++; }
   return hero;
  }
  private Hero ByName(string name)
  {
   string key=NpcDataFileName.NormalizeDisplayName(name);
   if (!_names.TryGetValue(key,out var hero))
   { hero=MemoryEntityIdentityBannerlordAdapter.ResolveUniqueHeroByNpcFileDisplayName(key);_names[key]=hero;UniqueNameLookups++; }
   return hero;
  }
  internal bool TryResolveNpcDataFileHeroIdForImport(string file,out string id,out string warning)
  { IdentityFiles++;return ResolveImportIdentity(file,out id,out warning,ById,ByName); }
  internal string ResolveHeroNameForNpcDataFile(string id)
  {
   string key=(id??"").Trim();
   if (!_fileNames.TryGetValue(key,out string name))
   { name=NpcDataIdentityFileAdapter.ResolveHeroNameForNpcDataFile(key);_fileNames[key]=name;FilenameLookups++; }
   return name;
  }
  internal void StampNpcPersonaProfile(string id,MyBehavior.NpcPersonaProfile profile)
   => PersonaImportOwner.StampProfileMetadata(id,profile,key=>ById(key)?.Name?.ToString());
  internal bool TryPrepareNpcPersonaProfileForWrite(string id,MyBehavior.NpcPersonaProfile profile)
  {
   if (string.IsNullOrWhiteSpace(id)||profile==null) return false;
   StampNpcPersonaProfile(id,profile);return true;
  }
 }
}
