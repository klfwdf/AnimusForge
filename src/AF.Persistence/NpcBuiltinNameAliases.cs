using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using Newtonsoft.Json;

namespace AnimusForge;

// Reviewed built-in CN/EN file-name pairs, keyed by the same hero identity.
// This is not a general permission to ignore a different NPC name.
internal static class NpcBuiltinNameAliases
{
    private static readonly Lazy<Dictionary<string, List<string[]>>> Pairs = new Lazy<Dictionary<string, List<string[]>>>(() =>
    {
        using (var stream = typeof(NpcBuiltinNameAliases).Assembly.GetManifestResourceStream("AnimusForge.Defaults.NpcBuiltinNameAliases.json"))
        using (var reader = new StreamReader(stream, Encoding.UTF8))
            return JsonConvert.DeserializeObject<Dictionary<string, List<string[]>>>(reader.ReadToEnd());
    });

    private static string Normalize(string name) => NpcDataFileName.NormalizeDisplayName((name ?? "").Replace('_', ' '));

    internal static bool Matches(string heroId, string fileName, string currentName)
    {
        if (NpcDataFileName.IsAutoGeneratedHeroId(heroId) || !Pairs.Value.TryGetValue(heroId ?? "", out var pairs)) return false;
        string file = Normalize(fileName), current = Normalize(currentName);
        foreach (var pair in pairs)
            if (pair.Length == 2 && (string.Equals(file, Normalize(pair[0]), StringComparison.OrdinalIgnoreCase)
                    && string.Equals(current, Normalize(pair[1]), StringComparison.OrdinalIgnoreCase)
                || string.Equals(file, Normalize(pair[1]), StringComparison.OrdinalIgnoreCase)
                    && string.Equals(current, Normalize(pair[0]), StringComparison.OrdinalIgnoreCase))) return true;
        return false;
    }
}
