using System;
using System.IO;

namespace AnimusForge;

/// <summary>
/// Naming contract for per-NPC JSON files under PlayerExports: "&lt;heroId&gt;__&lt;displayName&gt;.json".
/// Pure string/path logic only; resolving a Hero from the parsed parts stays with the host
/// (it needs live campaign objects).
/// </summary>
internal static class NpcDataFileName
{
	internal const string Separator = "__";
	internal const string UnknownHeroId = "unknown";
	internal const string DefaultDisplayName = "NPC";
	internal const string AutoGeneratedHeroIdPrefix = "CharacterObject_";

	internal static bool IsAutoGeneratedHeroId(string heroId)
	{
		string text = (heroId ?? "").Trim();
		return text.StartsWith(AutoGeneratedHeroIdPrefix, StringComparison.OrdinalIgnoreCase);
	}

	/// <summary>Parses "id__name"; false when there is no separator or the id part is empty.</summary>
	internal static bool TryParseParts(string filePath, out string heroId, out string displayName)
	{
		heroId = "";
		displayName = "";
		try
		{
			string text = Path.GetFileNameWithoutExtension(filePath) ?? "";
			int num = text.IndexOf(Separator, StringComparison.Ordinal);
			if (num <= 0)
			{
				return false;
			}
			heroId = (text.Substring(0, num) ?? "").Trim();
			displayName = ((num + 2 < text.Length) ? text.Substring(num + 2) : "").Trim();
			return !string.IsNullOrEmpty(heroId);
		}
		catch
		{
			heroId = "";
			displayName = "";
			return false;
		}
	}

	internal static string TryParseHeroId(string filePath)
	{
		return TryParseParts(filePath, out var heroId, out var _) ? heroId : null;
	}

	/// <summary>Invalid file-name chars → '_', runs of spaces collapsed, trimmed.</summary>
	internal static string NormalizeDisplayName(string value)
	{
		string text = (value ?? "").Trim();
		if (string.IsNullOrWhiteSpace(text))
		{
			return "";
		}
		try
		{
			foreach (char oldChar in Path.GetInvalidFileNameChars())
			{
				text = text.Replace(oldChar, '_');
			}
		}
		catch
		{
		}
		while (text.Contains("  "))
		{
			text = text.Replace("  ", " ");
		}
		return text.Trim();
	}

	/// <summary>A display name that carries information (not blank, not the "NPC"/"unknown" placeholders).</summary>
	internal static bool IsDisplayNameSpecified(string displayName)
	{
		string text = NormalizeDisplayName(displayName);
		return !string.IsNullOrWhiteSpace(text)
			&& !string.Equals(text, DefaultDisplayName, StringComparison.OrdinalIgnoreCase)
			&& !string.Equals(text, UnknownHeroId, StringComparison.OrdinalIgnoreCase);
	}

	/// <summary>
	/// Legacy compatibility rule: a null hero or an unspecified file name is compatible unless
	/// <paramref name="strictWhenNameMissing"/>; otherwise the normalized names must match (case-insensitive).
	/// </summary>
	internal static bool IsDisplayNameCompatible(string fileDisplayName, string heroName, bool heroExists, bool strictWhenNameMissing)
	{
		if (!heroExists)
		{
			return !strictWhenNameMissing;
		}
		if (!IsDisplayNameSpecified(fileDisplayName))
		{
			return !strictWhenNameMissing;
		}
		string text = NormalizeDisplayName(fileDisplayName);
		string text2 = NormalizeDisplayName(heroName ?? "");
		return !string.IsNullOrWhiteSpace(text2) && string.Equals(text, text2, StringComparison.OrdinalIgnoreCase);
	}

	/// <summary>Builds "id__name.json" with placeholders for blank id/name and invalid chars replaced.</summary>
	internal static string Build(string heroId, string heroName)
	{
		string id = (heroId ?? "").Trim();
		if (string.IsNullOrEmpty(id))
		{
			id = UnknownHeroId;
		}
		string text = heroName ?? "";
		if (string.IsNullOrWhiteSpace(text))
		{
			text = DefaultDisplayName;
		}
		string text2 = id + Separator + text;
		char[] invalidFileNameChars = Path.GetInvalidFileNameChars();
		foreach (char oldChar in invalidFileNameChars)
		{
			text2 = text2.Replace(oldChar, '_');
		}
		return text2 + ".json";
	}
}
