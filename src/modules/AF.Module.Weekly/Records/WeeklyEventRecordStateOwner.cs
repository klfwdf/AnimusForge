internal static string BuildPublishedWorldWeeklyProductState(EventRecordEntry entry)
	{
		if (entry == null
			|| !string.Equals((entry.EventKind ?? "").Trim(), "world", StringComparison.OrdinalIgnoreCase)
			|| !string.IsNullOrWhiteSpace(entry.ScopeKingdomId))
		{
			return "";
		}
		string sourceId = (entry.EventId ?? "").Trim();
		string report = (entry.Summary ?? "").Trim();
		if (!sourceId.StartsWith("weekly_report:world:", StringComparison.OrdinalIgnoreCase) || string.IsNullOrWhiteSpace(report))
		{
			return "";
		}
		StringBuilder stringBuilder = new StringBuilder(sourceId.Length + report.Length + (entry.Title?.Length ?? 0) + 48);
		AppendPublishedWorldWeeklyProductField(stringBuilder, sourceId);
		stringBuilder.Append(Math.Max(0, entry.WeekIndex)).Append('|');
		AppendPublishedWorldWeeklyProductField(stringBuilder, (entry.Title ?? "").Trim());
		AppendPublishedWorldWeeklyProductField(stringBuilder, report);
		return stringBuilder.ToString();
	}

internal static void AppendPublishedWorldWeeklyProductField(StringBuilder builder, string value)
	{
		string text = value ?? "";
		builder.Append(text.Length).Append(':').Append(text).Append('|');
	}

internal void NotifyPublishedWorldWeeklyProductChanged(string previousProductState, EventRecordEntry currentEntry)
	{
		string currentProductState = BuildPublishedWorldWeeklyProductState(currentEntry);
		if (!string.Equals(previousProductState ?? "", currentProductState, StringComparison.Ordinal))
		{
			Interlocked.Increment(ref PublishedHistoryRevision);
		}
	}
internal static List<string> SelectWeeklyShortReportKingdomIdsFromSnapshot(string npcKingdomId, bool excludeNpcKingdom, bool npcKingdomEligible, IEnumerable<string> proximityOrderedKingdomIds, IEnumerable<string> fallbackKingdomIds)
	{
		string text = (npcKingdomId ?? "").Trim();
		List<string> list = (proximityOrderedKingdomIds ?? Enumerable.Empty<string>()).Where((string x) => !string.IsNullOrWhiteSpace(x)).Select((string x) => x.Trim()).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
		if (list.Count == 0)
		{
			list = (fallbackKingdomIds ?? Enumerable.Empty<string>()).Where((string x) => !string.IsNullOrWhiteSpace(x)).Select((string x) => x.Trim()).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
		}
		if (excludeNpcKingdom && !string.IsNullOrWhiteSpace(text))
		{
			list.RemoveAll((string x) => string.Equals((x ?? "").Trim(), text, StringComparison.OrdinalIgnoreCase));
		}
		List<string> list2 = list.Take(3).ToList();
		if (!excludeNpcKingdom && npcKingdomEligible && !string.IsNullOrWhiteSpace(text) && !list2.Any((string x) => string.Equals((x ?? "").Trim(), text, StringComparison.OrdinalIgnoreCase)))
		{
			if (list2.Count >= 3)
			{
				list2.RemoveAt(list2.Count - 1);
			}
			list2.Insert(0, text);
		}
		return list2.Where((string x) => !string.IsNullOrWhiteSpace(x)).Select((string x) => x.Trim()).Distinct(StringComparer.OrdinalIgnoreCase).Take(3).ToList();
	}

internal static string BuildWeeklyEpicWeekLabel(int weekIndex, Func<int,string> calendarDate) => weekIndex <= 0 ? "开局" : calendarDate(WeeklyReportSchedulePolicy.GetEndDay(weekIndex));

internal string GetPreviousWeeklyReportText(WeeklyEventMaterialPreviewGroup group, int currentWeekIndex, Func<int,string> calendarDate)
	{
		string text = (group?.GroupKind ?? "").Trim();
		string text2 = (group?.KingdomId ?? "").Trim();
		EventRecordEntry eventRecordEntry = WeeklyEventDataImportOwner.SanitizeEventRecordEntries(Records, WeeklyGenerationRules.NeutralizeWeeklyReportScenarioName, WeeklyGenerationRules.BuildFallbackWeeklyReportShortSummary, WeeklyGenerationRules.NormalizeWeeklyReportTagText).FirstOrDefault((EventRecordEntry x) => x != null && x.WeekIndex == currentWeekIndex - 1 && string.Equals((x.EventKind ?? "").Trim(), text, StringComparison.OrdinalIgnoreCase) && string.Equals((x.ScopeKingdomId ?? "").Trim(), text2, StringComparison.OrdinalIgnoreCase));
		if (eventRecordEntry == null)
		{
			return "无";
		}
		string text3 = WeeklyGenerationRules.BuildFallbackWeeklyReportShortSummary(eventRecordEntry.ShortSummary);
		if (string.IsNullOrWhiteSpace(text3))
		{
			text3 = WeeklyGenerationRules.BuildFallbackWeeklyReportShortSummary(eventRecordEntry.Summary);
		}
		if (string.IsNullOrWhiteSpace(text3))
		{
			return "无";
		}
		return WeeklyGenerationRules.NeutralizeWeeklyReportScenarioName(BuildWeeklyEpicWeekLabel(eventRecordEntry.WeekIndex, calendarDate) + "短摘要：" + text3);
	}

internal static string BuildDefaultWeeklyReportTitle(WeeklyEventMaterialPreviewGroup group, int weekIndex, Func<int,string> calendarDate, Func<string,string> kingdomDisplay)
	{
		string text = BuildWeeklyEpicWeekLabel(weekIndex, calendarDate);
		if (string.Equals((group?.GroupKind ?? "").Trim(), "world", StringComparison.OrdinalIgnoreCase))
		{
			return text + "世界周报";
		}
		string text2 = kingdomDisplay(group?.KingdomId);
		if (string.IsNullOrWhiteSpace(text2))
		{
			text2 = "某王国";
		}
		return text2 + text + "周报";
	}

