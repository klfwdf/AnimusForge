internal void TryStartDeferredAutoWeeklyReports()
	{
		_port.SynchronizeNewsCollectionMode?.Invoke();
		if (_port.HasRestartedWeeklyCollection?.Invoke() == true || !_port.IsCurrentOwner()) return;
		if (_port.AutoSchedule.PendingWeek <= 0 || _weeklyReportGenerationInProgress || _port.RebellionFlow())
		{
			return;
		}
		DuelSettings settings = DuelSettings.GetSettings();
		if (settings == null || !settings.IsLegacyWeeklyAutoGenerationActive())
		{
			return;
		}
		int currentGameDayIndexSafe = _port.CurrentDay();
		int missingWeek = _port.AutoSchedule.ResolvePendingWeek(_lastAutoGeneratedWeeklyReportWeek,
			currentGameDayIndexSafe, _weeklyReportGenerationInProgress,
			settings != null && settings.IsLegacyWeeklyAutoGenerationActive(), _port.RebellionFlow());
		if (missingWeek <= 0)
		{
			return;
		}
		if (CampaignDailyMaintenanceController.IsDeferredDailyMaintenanceEnabled())
		{
			_port.QueueDeferredWeekly(_port.AutoSchedule.PendingWeek, currentGameDayIndexSafe, "deferred_auto_weekly_resume");
		}
		else
		{
			StartAutoWeeklyReportsForWeek(missingWeek, currentGameDayIndexSafe);
		}
	}

internal async Task GenerateAutoWeeklyReportsAsync(List<WeeklyEventMaterialPreviewGroup> groups, int weekIndex, int startDay, int endDay, List<WeeklyReportBatchRequest> preparedBatches = null, WeeklyReportMaterialRevisionOwner.Snapshot sourceSnapshotOverride = null)
	{
		long runtimeGeneration = _port.CaptureGeneration();
		int newsEpoch = _port.NewsEpoch;
		try
		{
			WeeklyReportGenerationResult weeklyReportGenerationResult = await GenerateWeeklyReportsMinuteBurstAsyncInternal(groups, weekIndex, startDay, endDay, _port.CalendarDate(endDay) + "自动周报", openViewerWhenDone: false, queueBlockingPopupOnFatalFailure: true, isAutoGeneration: true, popupCandidateKingdomIdsOverride: null, preparedBatches: preparedBatches, runtimeGeneration: runtimeGeneration, sourceSnapshotOverride: sourceSnapshotOverride);
			if (_port.IsCurrentOwner() && !_port.IsStale(runtimeGeneration, "auto_weekly_report_complete") && weeklyReportGenerationResult != null && weeklyReportGenerationResult.Completed && !weeklyReportGenerationResult.BlockedByFatalFailure)
			{
				_port.QueueMainThreadAction(() => {
					if (!_port.IsCurrentNewsEpoch(newsEpoch) || !_port.IsCurrentGeneration(runtimeGeneration) || !_port.IsCurrentOwner()) return;
					_lastAutoGeneratedWeeklyReportWeek = Math.Max(_lastAutoGeneratedWeeklyReportWeek, weekIndex);
					_port.CompleteRestartedWeeklyCollection();
				});
			}
		}
		catch (Exception ex)
		{
			Logger.Log("EventWeeklyReport", "[ERROR] GenerateAutoWeeklyReportsAsync failed: " + ex);
		}
		finally
		{
			if (_port.IsCurrentOwner() && _port.IsCurrentGeneration(runtimeGeneration))
			{
				_port.QueueMainThreadAction(() => {
					if (_port.IsCurrentNewsEpoch(newsEpoch) && _port.IsCurrentGeneration(runtimeGeneration) && _port.IsCurrentOwner()) _weeklyReportGenerationInProgress = false;
				});
			}
		}
	}

