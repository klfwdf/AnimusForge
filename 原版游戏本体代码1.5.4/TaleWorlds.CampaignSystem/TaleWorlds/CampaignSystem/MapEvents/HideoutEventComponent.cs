using System.Collections.Generic;
using System.Linq;
using Helpers;
using TaleWorlds.CampaignSystem.Actions;
using TaleWorlds.CampaignSystem.Encounters;
using TaleWorlds.CampaignSystem.GameMenus;
using TaleWorlds.CampaignSystem.Party;
using TaleWorlds.CampaignSystem.Roster;
using TaleWorlds.CampaignSystem.Settlements;
using TaleWorlds.Core;
using TaleWorlds.Library;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.MapEvents;

public class HideoutEventComponent : MapEventComponent
{
	public enum HideoutBattleEndState
	{
		None,
		Retreated,
		Defeated,
		Victory,
		SendTroops
	}

	[SaveableField(1)]
	public readonly bool IsSendTroops;

	[SaveableProperty(2)]
	public int InitialHideoutPopulation { get; private set; }

	public override MapEvent.PowerCalculationContext SimulationContext => Campaign.Current.Models.MilitaryPowerModel.GetContextForPosition(base.MapEvent.Position);

	internal static void AutoGeneratedStaticCollectObjectsHideoutEventComponent(object o, List<object> collectedObjects)
	{
		((HideoutEventComponent)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected override void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		base.AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	internal static object AutoGeneratedGetMemberValueInitialHideoutPopulation(object o)
	{
		return ((HideoutEventComponent)o).InitialHideoutPopulation;
	}

	internal static object AutoGeneratedGetMemberValueIsSendTroops(object o)
	{
		return ((HideoutEventComponent)o).IsSendTroops;
	}

	private HideoutEventComponent(MapEvent mapEvent, bool isSendTroops)
		: base(mapEvent)
	{
		IsSendTroops = isSendTroops;
	}

	public static HideoutEventComponent CreateHideoutEvent(PartyBase attackerParty, PartyBase defenderParty, bool isSendTroops)
	{
		MapEvent mapEvent = new MapEvent();
		HideoutEventComponent hideoutEventComponent = new HideoutEventComponent(mapEvent, isSendTroops);
		mapEvent.Initialize(attackerParty, defenderParty, hideoutEventComponent);
		hideoutEventComponent.SetInitialHideoutPopulation();
		Campaign.Current.MapEventManager.OnMapEventCreated(mapEvent);
		return hideoutEventComponent;
	}

	public static HideoutEventComponent CreateComponentForOldSaves(MapEvent mapEvent, bool isSendTroops)
	{
		return new HideoutEventComponent(mapEvent, isSendTroops)
		{
			InitialHideoutPopulation = 20
		};
	}

	public override MapEvent.BattleTypes GetBattleType()
	{
		return MapEvent.BattleTypes.Hideout;
	}

	public override void OnBeforeMapEventFinalize()
	{
		BattleSideEnum battleSideEnum = ((base.MapEvent.BattleState == BattleState.AttackerVictory) ? BattleSideEnum.Attacker : BattleSideEnum.Defender);
		HideoutBattleEndState battleEndState = ((!base.MapEvent.HasWinner) ? HideoutBattleEndState.Retreated : ((battleSideEnum != base.MapEvent.PlayerSide) ? HideoutBattleEndState.Defeated : ((!IsSendTroops) ? HideoutBattleEndState.Victory : HideoutBattleEndState.SendTroops)));
		CampaignEventDispatcher.Instance.OnHideoutBattleCompleted(battleSideEnum, this, battleEndState);
	}

	public override void OnAddInvolvedParty(MapEventParty party, BattleSideEnum side)
	{
		if (party.Party == MobileParty.MainParty.Party)
		{
			party.Party.MobileParty.SetMoveModeHold();
		}
	}

	public override void AddInsideSettlementParties()
	{
		MapEventComponentHelper.AddInsideSettlementParties(base.MapEvent);
	}

	public override bool TryHandlePlayerEncounterEnd(bool isPlayerAttacker)
	{
		switch (base.MapEvent.BattleState)
		{
		case BattleState.AttackerVictory:
			OnHideoutCleared(base.MapEventSettlement);
			break;
		case BattleState.None:
			EncounterManager.StartSettlementEncounter(MobileParty.MainParty, base.MapEventSettlement);
			GameMenu.SwitchToMenu("hideout_after_defeated_and_saved");
			break;
		}
		return true;
	}

	private void OnHideoutCleared(Settlement hideout)
	{
		foreach (MobileParty item in hideout.Parties.ToList())
		{
			if (item.Army == null || item.Army.LeaderParty == item)
			{
				LeaveSettlementAction.ApplyForParty(item);
			}
			item.Ai.SetDoNotAttackMainParty(3);
		}
		hideout.IsVisible = false;
	}

	public override PlayerEncounterState GetPlayerEncounterStateOnMapEventEnd()
	{
		if (base.MapEvent.WinningSide == PartyBase.MainParty.Side)
		{
			return PlayerEncounterState.PlayerVictory;
		}
		if (base.MapEvent.DefeatedSide == PartyBase.MainParty.Side)
		{
			return PlayerEncounterState.PlayerTotalDefeat;
		}
		return PlayerEncounterState.End;
	}

	public override bool CheckIfBattleShouldContinueAfterBattleMission(CampaignBattleResult campaignBattleResult)
	{
		return false;
	}

	public override void UpdatePlayerEncounterState(CampaignBattleResult campaignBattleResult, out PlayerEncounterState encounterState, out bool stateHandled)
	{
		encounterState = PlayerEncounter.Current.EncounterState;
		stateHandled = false;
		MapEvent mapEvent = base.MapEvent;
		if (campaignBattleResult != null && campaignBattleResult.BattleResolved)
		{
			if (campaignBattleResult.PlayerVictory)
			{
				mapEvent?.SetOverrideWinner(PartyBase.MainParty.Side);
			}
			else
			{
				bool flag = true;
				if (mapEvent != null && mapEvent.IsHideoutBattle)
				{
					mapEvent.MapEventSettlement.Hideout.SetNextPossibleAttackTime(Campaign.Current.Models.HideoutModel.HideoutHiddenDuration);
					if (mapEvent.GetMapEventSide(PlayerEncounter.Current.PlayerSide).RecalculateMemberCountOfSide() > 0)
					{
						flag = false;
					}
				}
				if (flag)
				{
					mapEvent?.SetOverrideWinner(PartyBase.MainParty.OpponentSide);
				}
			}
			encounterState = PlayerEncounterState.PrepareResults;
		}
		else if (PlayerEncounter.Current.BattleSimulation != null && (PlayerEncounter.BattleState == BattleState.AttackerVictory || PlayerEncounter.BattleState == BattleState.DefenderVictory))
		{
			if (mapEvent.WinningSide == PlayerEncounter.Current.PlayerSide && PlayerEncounter.Battle.RetreatingSide == BattleSideEnum.None)
			{
				PlayerEncounter.EnemySurrender = true;
			}
			else
			{
				int totalManCount = MobileParty.MainParty.MemberRoster.TotalManCount;
				int totalWounded = MobileParty.MainParty.MemberRoster.TotalWounded;
				if (totalManCount - totalWounded == 0)
				{
					PlayerEncounter.PlayerSurrender = true;
				}
			}
			encounterState = PlayerEncounterState.PrepareResults;
		}
		else if (mapEvent != null && PlayerEncounter.PlayerSurrender && mapEvent.HasWinner)
		{
			encounterState = PlayerEncounterState.PrepareResults;
		}
		else if (IsSendTroops && mapEvent.HasWinner && mapEvent.WinningSide == BattleSideEnum.Attacker)
		{
			encounterState = PlayerEncounterState.End;
			OnHideoutCleared(mapEvent.MapEventSettlement);
			stateHandled = true;
		}
		else
		{
			stateHandled = true;
			if (PlayerEncounter.Current.IsJoinedBattle && Campaign.Current.CurrentMenuContext != null && Campaign.Current.CurrentMenuContext.GameMenu.StringId == "join_encounter")
			{
				PlayerEncounter.LeaveBattle();
			}
			if (mapEvent != null && mapEvent.IsHideoutBattle)
			{
				mapEvent.MapEventSettlement.Hideout.SetNextPossibleAttackTime(Campaign.Current.Models.HideoutModel.HideoutHiddenDuration);
			}
		}
	}

	public override void OnPlayerEncounterContinueBattle(CampaignBattleResult campaignBattleResult, out PlayerEncounterState nextEncounterState, out bool stateHandled)
	{
		MapEventComponentHelper.OnPlayerEncounterContinueBattleCommon(base.MapEvent, campaignBattleResult, out nextEncounterState, out stateHandled);
	}

	public override void UpdateMapEventSettlement()
	{
		base.MapEventSettlement = base.MapEvent.DefenderSide.LeaderParty.Settlement;
	}

	public override void OnPlayerEncounterFinalizeBattle()
	{
		if (base.MapEvent.HasWinner || base.MapEvent.DiplomaticallyFinished)
		{
			PlayerEncounter.Current.FinalizeBattleFromComponent();
		}
		else
		{
			PlayerEncounter.LeaveBattle();
		}
	}

	public override CampaignVec2 GetMapEventPosition()
	{
		return base.MapEvent.AttackerSide.LeaderParty.Position;
	}

	public override void OnAfterLoad()
	{
		if (MBSaveLoad.LastLoadedGameVersion.IsOlderThan(ApplicationVersion.FromString("v1.3.15.110431")))
		{
			InitialHideoutPopulation = 20;
		}
	}

	private void SetInitialHideoutPopulation()
	{
		foreach (MapEventParty item in base.MapEvent.PartiesOnSide(BattleSideEnum.Defender))
		{
			PartyBase party = item.Party;
			MobileParty mobileParty = party.MobileParty;
			if (mobileParty == null || !mobileParty.IsBandit)
			{
				continue;
			}
			foreach (TroopRosterElement item2 in party.MemberRoster.GetTroopRoster())
			{
				int num = item2.Number - item2.WoundedNumber;
				InitialHideoutPopulation += num;
			}
		}
	}
}
