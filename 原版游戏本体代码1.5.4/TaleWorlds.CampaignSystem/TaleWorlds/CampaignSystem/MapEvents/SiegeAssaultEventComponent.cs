using System.Collections.Generic;
using TaleWorlds.CampaignSystem.Actions;
using TaleWorlds.CampaignSystem.Encounters;
using TaleWorlds.CampaignSystem.GameMenus;
using TaleWorlds.CampaignSystem.Party;
using TaleWorlds.CampaignSystem.Siege;
using TaleWorlds.Core;
using TaleWorlds.Library;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.MapEvents;

public class SiegeAssaultEventComponent : MapEventComponent
{
	private bool _keepSiegeEvent;

	private bool _isSiegeCompleted;

	private bool _isSiegeWon;

	[SaveableField(100)]
	private MapEvent.BattleTypes _eventType = MapEvent.BattleTypes.Siege;

	public override MapEvent.PowerCalculationContext SimulationContext => MapEvent.PowerCalculationContext.Siege;

	internal static void AutoGeneratedStaticCollectObjectsSiegeAssaultEventComponent(object o, List<object> collectedObjects)
	{
		((SiegeAssaultEventComponent)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected override void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		base.AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	internal static object AutoGeneratedGetMemberValue_eventType(object o)
	{
		return ((SiegeAssaultEventComponent)o)._eventType;
	}

	public static SiegeAssaultEventComponent CreateSiegeAssaultMapEvent(PartyBase attackerParty, PartyBase defenderParty)
	{
		MapEvent mapEvent = new MapEvent();
		SiegeAssaultEventComponent siegeAssaultEventComponent = new SiegeAssaultEventComponent(mapEvent);
		mapEvent.Initialize(attackerParty, defenderParty, siegeAssaultEventComponent);
		Campaign.Current.MapEventManager.OnMapEventCreated(mapEvent);
		siegeAssaultEventComponent._eventType = MapEvent.BattleTypes.Siege;
		return siegeAssaultEventComponent;
	}

	public override bool TryHandlePlayerEncounterEnd(bool isPlayerAttacker)
	{
		if (base.MapEventSettlement != null && _eventType == MapEvent.BattleTypes.Siege && isPlayerAttacker)
		{
			EncounterManager.StartSettlementEncounter((MobileParty.MainParty.Army != null) ? MobileParty.MainParty.Army.LeaderParty : MobileParty.MainParty, base.MapEventSettlement);
			GameMenu.SwitchToMenu("menu_settlement_taken");
		}
		return true;
	}

	public override PlayerEncounterState GetPlayerEncounterStateOnMapEventEnd()
	{
		if (base.MapEvent.WinningSide == PartyBase.MainParty.Side)
		{
			return PlayerEncounterState.PlayerVictory;
		}
		if (base.MapEvent.DefeatedSide == PartyBase.MainParty.Side)
		{
			return PlayerEncounterState.PlayerTotalDefeat;
		}
		return PlayerEncounterState.End;
	}

	public override bool CheckIfBattleShouldContinueAfterBattleMission(CampaignBattleResult campaignBattleResult)
	{
		MapEventSide mapEventSide = base.MapEvent.GetMapEventSide(base.MapEvent.PlayerSide);
		if (PlayerEncounter.PlayerSurrender || campaignBattleResult == null || (campaignBattleResult.EnemyRetreated && mapEventSide.OtherSide != base.MapEvent.AttackerSide))
		{
			return false;
		}
		bool num = base.MapEvent.BattleState == BattleState.AttackerVictory;
		bool flag = !base.MapEvent.CheckIfOneSideHasLost();
		if (base.MapEvent.DefeatedSide != BattleSideEnum.None)
		{
			MapEventSide mapEventSide2 = base.MapEvent.GetMapEventSide(base.MapEvent.DefeatedSide);
			bool num2 = campaignBattleResult.PlayerDefeat || campaignBattleResult.PlayerVictory || campaignBattleResult.EnemyPulledBack;
			bool flag2 = mapEventSide2.GetTotalHealthyTroopCountOfSide() + mapEventSide2.GetTotalHealthyHeroCountOfSide() >= 1;
			flag = num2 && flag2;
		}
		if (!num && flag)
		{
			return !mapEventSide.IsSurrendered;
		}
		return false;
	}

	public override void UpdatePlayerEncounterState(CampaignBattleResult campaignBattleResult, out PlayerEncounterState nextEncounterState, out bool stateHandled)
	{
		nextEncounterState = PlayerEncounter.Current.EncounterState;
		stateHandled = false;
		MapEvent mapEvent = base.MapEvent;
		if (mapEvent != null)
		{
			mapEvent.CheckIfOneSideHasLost();
			campaignBattleResult = CampaignBattleResult.GetResult(mapEvent.BattleState);
		}
		if (campaignBattleResult != null && campaignBattleResult.BattleResolved)
		{
			if (campaignBattleResult.PlayerVictory)
			{
				mapEvent?.SetOverrideWinner(PartyBase.MainParty.Side);
			}
			else
			{
				mapEvent?.SetOverrideWinner(PartyBase.MainParty.OpponentSide);
			}
			nextEncounterState = PlayerEncounterState.PrepareResults;
		}
		else if (PlayerEncounter.Current.BattleSimulation != null && (PlayerEncounter.BattleState == BattleState.AttackerVictory || PlayerEncounter.BattleState == BattleState.DefenderVictory))
		{
			if (mapEvent.WinningSide == PlayerEncounter.Current.PlayerSide && PlayerEncounter.Battle.RetreatingSide == BattleSideEnum.None)
			{
				PlayerEncounter.EnemySurrender = true;
			}
			else
			{
				int totalManCount = MobileParty.MainParty.MemberRoster.TotalManCount;
				int totalWounded = MobileParty.MainParty.MemberRoster.TotalWounded;
				if (totalManCount - totalWounded == 0)
				{
					PlayerEncounter.PlayerSurrender = true;
				}
			}
			nextEncounterState = PlayerEncounterState.PrepareResults;
		}
		else if (PlayerEncounter.Current.BattleSimulation != null && PlayerEncounter.Current.BattleSimulation.IsSimulationFinished && mapEvent?.MapEventSettlement != null && PlayerEncounter.BattleState == BattleState.None && PlayerSiege.PlayerSiegeEvent != null)
		{
			stateHandled = true;
			PlayerSiege.PlayerSiegeEvent.BreakSiegeEngine(PlayerSiege.PlayerSiegeEvent.GetSiegeEventSide(mapEvent.PlayerSide), DefaultSiegeEngineTypes.Preparations);
		}
		else if (mapEvent != null && mapEvent.HasWinner)
		{
			nextEncounterState = PlayerEncounterState.PrepareResults;
		}
		else
		{
			stateHandled = true;
			if (PlayerEncounter.Current.IsJoinedBattle && Campaign.Current.CurrentMenuContext != null && Campaign.Current.CurrentMenuContext.GameMenu.StringId == "join_encounter")
			{
				PlayerEncounter.LeaveBattle();
			}
		}
	}

	public override void OnPlayerEncounterContinueBattle(CampaignBattleResult campaignBattleResult, out PlayerEncounterState nextEncounterState, out bool stateHandled)
	{
		MapEvent mapEvent = base.MapEvent;
		nextEncounterState = PlayerEncounter.Current.EncounterState;
		MapEventSide otherSide = mapEvent.GetMapEventSide(mapEvent.PlayerSide).OtherSide;
		mapEvent.ApplyGainedVariablesOnPlayerBattleContinues();
		mapEvent.SetOverrideWinner(BattleSideEnum.None);
		if (otherSide == mapEvent.AttackerSide && campaignBattleResult != null && campaignBattleResult.EnemyRetreated)
		{
			FinishBattleAndKeepSiegeEvent();
			PlayerEncounter.Current.FinalizeBattleFromComponent();
			GameMenu.ActivateGameMenu("menu_siege_strategies");
		}
		stateHandled = true;
	}

	public override void UpdateMapEventSettlement()
	{
		base.MapEventSettlement = base.MapEvent.AttackerSide.LeaderParty.SiegeEvent.BesiegedSettlement;
	}

	public override void OnPlayerEncounterFinalizeBattle()
	{
		if (base.MapEvent.HasWinner || base.MapEvent.DiplomaticallyFinished)
		{
			PlayerEncounter.Current.FinalizeBattleFromComponent();
		}
		else
		{
			PlayerEncounter.LeaveBattle();
		}
	}

	protected override void OnInitialize()
	{
		if ((base.MapEvent.AttackerSide.LeaderParty.MobileParty == MobileParty.MainParty || base.MapEvent.DefenderSide.LeaderParty.MobileParty == MobileParty.MainParty) && base.MapEvent.DefenderSide.LeaderParty.IsSettlement && base.MapEvent.DefenderSide.LeaderParty.Settlement.IsFortification)
		{
			Debug.Print(string.Concat("A siege mapEvent has been started on ", base.MapEvent.DefenderSide.LeaderParty.Name, "\n"), 0, Debug.DebugColor.DarkCyan, 64uL);
		}
	}

	public override void AddMapEventParties()
	{
		foreach (PartyBase item in base.MapEvent.MapEventSettlement.SiegeEvent.BesiegerCamp.GetInvolvedPartiesForEventType())
		{
			if (item.MapEventSide == null && (item != PartyBase.MainParty || item.MobileParty.Army != null) && (item.MobileParty.Army == null || item.MobileParty.Army.LeaderParty == item.MobileParty))
			{
				item.MapEventSide = base.MapEvent.AttackerSide.LeaderParty.MapEventSide;
			}
		}
		PartyBase leaderParty = base.MapEvent.DefenderSide.LeaderParty;
		PartyBase leaderParty2 = base.MapEvent.AttackerSide.LeaderParty;
		if (!leaderParty.IsMobile || leaderParty.MobileParty.BesiegedSettlement == null)
		{
			return;
		}
		List<PartyBase> involvedPartiesForEventType = leaderParty.MobileParty.SiegeEvent.GetInvolvedPartiesForEventType(MapEvent.BattleTypes.Siege);
		PartyBase partyBase = leaderParty2;
		foreach (PartyBase item2 in involvedPartiesForEventType)
		{
			if (item2 != partyBase && item2.IsMobile && item2 != PartyBase.MainParty && item2.MobileParty.BesiegedSettlement == leaderParty.MobileParty.BesiegedSettlement && (item2.MobileParty.Army == null || item2.MobileParty.Army.LeaderParty == item2.MobileParty))
			{
				item2.MapEventSide = base.MapEvent.DefenderSide;
			}
		}
	}

	public override CampaignVec2 GetMapEventPosition()
	{
		return base.MapEvent.AttackerSide.LeaderParty.Position;
	}

	private SiegeAssaultEventComponent(MapEvent mapEvent)
		: base(mapEvent)
	{
	}

	public override MapEvent.BattleTypes GetBattleType()
	{
		return _eventType;
	}

	public override void OnBeforeMapEventFinalize()
	{
		if (base.MapEvent.BattleState != BattleState.None && base.MapEventSettlement.SiegeEvent != null)
		{
			base.MapEventSettlement.SiegeEvent.OnBeforeSiegeEventEnd(base.MapEvent.BattleState, base.MapEvent.EventType);
		}
		if (!_keepSiegeEvent)
		{
			switch (base.MapEvent.BattleState)
			{
			case BattleState.AttackerVictory:
				CampaignEventDispatcher.Instance.SiegeCompleted(base.MapEventSettlement, base.MapEvent.AttackerSide.LeaderParty.MobileParty, isWin: true, base.MapEvent.EventType);
				_isSiegeWon = true;
				break;
			case BattleState.DefenderVictory:
				base.MapEventSettlement.SiegeEvent?.BesiegerCamp.RemoveAllSiegeParties();
				CampaignEventDispatcher.Instance.SiegeCompleted(base.MapEventSettlement, base.MapEvent.AttackerSide.LeaderParty.MobileParty, isWin: false, base.MapEvent.EventType);
				break;
			}
			if (base.MapEvent.BattleState == BattleState.AttackerVictory || base.MapEvent.BattleState == BattleState.DefenderVictory)
			{
				_isSiegeCompleted = true;
			}
		}
	}

	public override void OnAddInvolvedParty(MapEventParty party, BattleSideEnum side)
	{
		if (party.Party.MobileParty != null && party.Party.MobileParty.CurrentSettlement == null && side == BattleSideEnum.Defender)
		{
			_eventType = MapEvent.BattleTypes.SiegeOutside;
		}
	}

	public override void AddInsideSettlementParties()
	{
		List<PartyBase> list = new List<PartyBase>();
		foreach (PartyBase item in base.MapEventSettlement.GetInvolvedPartiesForEventType(base.MapEvent.EventType))
		{
			if (item != PartyBase.MainParty && item.MobileParty?.AttachedTo != MobileParty.MainParty)
			{
				list.Add(item);
			}
		}
		foreach (PartyBase item2 in list)
		{
			if (base.MapEventSettlement.SiegeEvent.CanPartyJoinSide(item2, BattleSideEnum.Defender))
			{
				item2.MapEventSide = base.MapEvent.DefenderSide;
			}
			else if (item2.MobileParty != null && !item2.MobileParty.IsGarrison && !item2.MobileParty.IsMilitia)
			{
				LeaveSettlementAction.ApplyForParty(item2.MobileParty);
				item2.MobileParty.SetMoveModeHold();
			}
		}
	}

	protected override void OnFinalize()
	{
		if (_isSiegeCompleted)
		{
			CampaignEventDispatcher.Instance.AfterSiegeCompleted(base.MapEventSettlement, base.MapEvent.AttackerSide.LeaderParty.MobileParty, _isSiegeWon, base.MapEvent.EventType);
		}
	}

	public void FinishBattleAndKeepSiegeEvent()
	{
		_keepSiegeEvent = true;
		base.MapEvent.AttackerSide.LeaderParty.MobileParty.RecalculateShortTermBehavior();
		base.MapEvent.FinishBattle();
	}

	public static SiegeAssaultEventComponent CreateComponentForOldSaves(MapEvent mapEvent)
	{
		return new SiegeAssaultEventComponent(mapEvent);
	}

	public override void OnAfterLoad()
	{
		if (_eventType == MapEvent.BattleTypes.None)
		{
			_eventType = MapEvent.BattleTypes.Siege;
		}
	}
}
