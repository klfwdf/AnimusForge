	private void SetPartyBaseEventLocalPosition(PartyBase party, BattleSideEnum side, int sideIndex)
	{
		UpdateValidLocalPositions(side, base.MapEvent.GetMapEventSide(side).Parties.Count);
		List<Vec2> list = ((side == BattleSideEnum.Attacker) ? _validLocalPositionsForAttackerSide : _validLocalPositionsForDefenderSide);
		if (list.Count == 0 || list.Count <= sideIndex)
		{
			party.MobileParty.EventPositionAdder = Vec2.Zero;
		}
		else
		{
			party.MobileParty.EventPositionAdder = list[sideIndex] + base.MapEvent.Position.ToVec2() - party.Position.ToVec2() - party.MobileParty.ArmyPositionAdder;
		}
	}

	private void UpdateValidLocalPositions(BattleSideEnum side, int sidePartyCount)
	{
		List<Vec2> list = ((side == BattleSideEnum.Attacker) ? _validLocalPositionsForAttackerSide : _validLocalPositionsForDefenderSide);
		if (!list.IsEmpty() && list.Count >= sidePartyCount)
		{
			return;
		}
		list.Clear();
		float eventDistance;
		Vec2 eventDirection = GetEventDirection(side, out eventDistance);
		int num = MathF.Max(30, sidePartyCount * 2);
		int num2 = 9;
		int num3 = 0;
		CampaignVec2 campaignVec = new CampaignVec2(base.MapEvent.Position.ToVec2(), !base.MapEvent.IsNavalMapEvent);
		do
		{
			float num4 = 1.2f;
			float num5 = 0.9f;
			float num6 = 1.6f;
			float num7 = 0.4f;
			int num8 = num3 / num2;
			int num9 = num3 % num2;
			float num10 = (base.MapEvent.IsNavalMapEvent ? num4 : num5);
			Vec2 vec = eventDirection * -1f * num10;
			Vec2 vec2 = ((float)num8 + 1f) * vec;
			if (!base.MapEvent.IsNavalMapEvent)
			{
				vec2 -= vec * 0.35f;
			}
			if (num9 == 0)
			{
				if (base.MapEvent.IsNavalMapEvent)
				{
					vec2 -= vec * 0.6f;
				}
				campaignVec.AddVec2(vec2);
				if (campaignVec.IsValid())
				{
					list.Add(vec2);
				}
			}
			else
			{
				Vec2 vec3 = ((num9 % 2 != 0) ? 1 : (-1)) * eventDirection.RightVec() * (base.MapEvent.IsNavalMapEvent ? num6 : num7);
				vec2 += vec3 * ((num9 + 1) / 2);
				campaignVec.AddVec2(vec2);
				if (campaignVec.IsValid())
				{
					list.Add(vec2);
				}
			}
			campaignVec.AddVec2(-vec2);
			num3++;
		}
		while (list.Count < num && num3 < 250);
		list.Sort((Vec2 x, Vec2 y) => x.Length.CompareTo(y.Length));
	}

	private Vec2 GetEventDirection(BattleSideEnum side, out float eventDistance)
	{
		MapEventSide mapEventSide = base.MapEvent.GetMapEventSide(side);
		Vec2 result = mapEventSide.OtherSide.LeaderParty.Position.ToVec2() - mapEventSide.LeaderParty.Position.ToVec2();
		if (result.Length < 1E-05f)
		{
			result = ((side != BattleSideEnum.Defender) ? base.MapEvent.GetLeaderParty(BattleSideEnum.Attacker).MobileParty.Bearing : (-base.MapEvent.GetLeaderParty(BattleSideEnum.Attacker).MobileParty.Bearing));
			result.Normalize();
			eventDistance = 0.1f;
		}
		else
		{
			result.Normalize();
			eventDistance = result.Length;
		}
		return result;
	}
