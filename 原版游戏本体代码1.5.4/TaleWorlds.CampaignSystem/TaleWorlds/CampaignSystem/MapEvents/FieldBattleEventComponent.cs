	}

	public static FieldBattleEventComponent CreateFieldBattleEvent(PartyBase attackerParty, PartyBase defenderParty)
	{
		MapEvent mapEvent = new MapEvent();
		FieldBattleEventComponent fieldBattleEventComponent = new FieldBattleEventComponent(mapEvent);
		mapEvent.Initialize(attackerParty, defenderParty, fieldBattleEventComponent);
		Campaign.Current.MapEventManager.OnMapEventCreated(mapEvent);
		return fieldBattleEventComponent;
	}

	public static FieldBattleEventComponent CreateComponentForOldSaves(MapEvent mapEvent)
	{
		return new FieldBattleEventComponent(mapEvent);
	}

	public override void OnBeforeMapEventFinalize()
	{
	}

	public override void OnAddInvolvedParty(MapEventParty party, BattleSideEnum side)
	{
		if (party.Party == MobileParty.MainParty.Party)
		{
			party.Party.MobileParty.SetMoveModeHold();
		}
		if (party.Party.IsMobile && party.Party.MobileParty.IsCurrentlyAtSea == base.MapEvent.IsNavalMapEvent && party.Party.MobileParty.BesiegedSettlement == null)
		{
			int sideIndex = base.MapEvent.GetMapEventSide(side).Parties.Count((MapEventParty p) => p.Party.IsMobile) - 1;
			SetPartyBaseEventLocalPosition(party.Party, side, sideIndex);
		}
	}

	public override void OnRemoveInvolvedParty(MapEventParty party)
	{
		if (!party.Party.IsMobile || party.Party.MobileParty.BesiegedSettlement != null)
		{
			return;
		}
		party.Party.MobileParty.EventPositionAdder = Vec2.Zero;
		MapEventSide[] sides = base.MapEvent.Sides;
		foreach (MapEventSide mapEventSide in sides)
		{
			for (int j = 0; j < mapEventSide.Parties.Count; j++)
			{
				if (mapEventSide.Parties[j].Party.IsMobile && mapEventSide.Parties[j].Party != mapEventSide.LeaderParty)
				{
					SetPartyBaseEventLocalPosition(mapEventSide.Parties[j].Party, mapEventSide.MissionSide, j);
				}
			}
		}
	}

	public override void UpdateAfterMapChange(MobileParty.NavigationType leaderNavigationCapability, MapEvent mapEvent)
	{
		foreach (PartyBase involvedParty in mapEvent.InvolvedParties)
		{
			if (involvedParty.IsMobile && involvedParty.MobileParty.CurrentSettlement == null && involvedParty.MobileParty.BesiegerCamp == null)
			{
				involvedParty.MobileParty.SetPositionAfterMapChange(mapEvent.Position);
			}
		}
	}

	public override void AddInsideSettlementParties()
	{
		if (base.MapEvent.MapEventSettlement != null)
		{
			MapEventComponentHelper.AddInsideSettlementParties(base.MapEvent);
		}
	}

	public override void AddNearbyPartiesToPlayerMapEvent()
	{
		MapEventComponentHelper.AddNearbyPartiesToPlayerMapEvent(base.MapEvent);
	}

	public override bool TryHandlePlayerEncounterEnd(bool isPlayerAttacker)
	{
		if (_isNavalEncounterFinishedWithDisengage)
		{
			GameMenu.ActivateGameMenu("naval_encounter_disengaged");
			return true;
		}
		return false;
	}

	public override PlayerEncounterState GetPlayerEncounterStateOnMapEventEnd()
	{
		if (base.MapEvent.WinningSide == PartyBase.MainParty.Side)
		{
			return PlayerEncounterState.PlayerVictory;
		}
		if (base.MapEvent.DefeatedSide == PartyBase.MainParty.Side && !_isNavalEncounterFinishedWithDisengage)
		{
			return PlayerEncounterState.PlayerTotalDefeat;
		}
		return PlayerEncounterState.End;
	}

	public override bool CheckIfBattleShouldContinueAfterBattleMission(CampaignBattleResult campaignBattleResult)
	{
		MapEventSide mapEventSide = base.MapEvent.GetMapEventSide(base.MapEvent.PlayerSide);
		if (PlayerEncounter.PlayerSurrender || campaignBattleResult == null || campaignBattleResult.EnemyRetreated)
		{
			return false;
		}
		bool flag = !base.MapEvent.CheckIfOneSideHasLost();
		if (base.MapEvent.DefeatedSide != BattleSideEnum.None)
		{
			MapEventSide mapEventSide2 = base.MapEvent.GetMapEventSide(base.MapEvent.DefeatedSide);
			bool num = campaignBattleResult.PlayerDefeat || campaignBattleResult.PlayerVictory || campaignBattleResult.EnemyPulledBack;
			bool flag2 = mapEventSide2.GetTotalHealthyTroopCountOfSide() + mapEventSide2.GetTotalHealthyHeroCountOfSide() >= 1;
			flag = num && flag2;
			if (base.MapEvent.IsNavalMapEvent && flag)
			{
				if (((base.MapEvent.DefeatedSide != BattleSideEnum.None) ? base.MapEvent.GetMapEventSide(base.MapEvent.DefeatedSide).Parties : base.MapEvent.PartiesOnSide(base.MapEvent.PlayerSide)).SumQ((MapEventParty t) => t.Ships.Count) - PlayerEncounter.Current.CapturedShipsInEncounter.Count <= 0)
				{
					return false;
				}
				if (((base.MapEvent.DefeatedSide != BattleSideEnum.None) ? base.MapEvent.GetMapEventSide(base.MapEvent.WinningSide).Parties : base.MapEvent.GetMapEventSide(base.MapEvent.PlayerSide.GetOppositeSide()).Parties).SumQ((MapEventParty t) => t.Ships.Count) == 0)
				{
					return false;
				}
				base.MapEvent.RecalculateStrengthOfSides();
				float num2 = base.MapEvent.StrengthOfSide[(int)base.MapEvent.PlayerSide];
				float num3 = base.MapEvent.StrengthOfSide[(int)base.MapEvent.PlayerSide.GetOppositeSide()];
				if ((PlayerEncounter.PlayerIsAttacker && num2 * 0.45f >= num3) || (PlayerEncounter.PlayerIsDefender && num2 <= num3 * 0.15f))
				{
					return false;
				}
				_isNavalEncounterFinishedWithDisengage = true;
				return false;
			}
		}
		if (flag && !mapEventSide.IsSurrendered)
		{
			return !_isNavalEncounterFinishedWithDisengage;
		}
		return false;
	}

	public override void UpdatePlayerEncounterState(CampaignBattleResult campaignBattleResult, out PlayerEncounterState encounterState, out bool stateHandled)
	{
		encounterState = PlayerEncounter.Current.EncounterState;
		stateHandled = false;
		MapEvent mapEvent = base.MapEvent;
		if (campaignBattleResult != null && campaignBattleResult.BattleResolved)
		{
			if (campaignBattleResult.PlayerVictory)
			{
				mapEvent?.SetOverrideWinner(PartyBase.MainParty.Side);
			}
			else
			{
				mapEvent?.SetOverrideWinner(PartyBase.MainParty.OpponentSide);
			}
			encounterState = PlayerEncounterState.PrepareResults;
		}
		else if (PlayerEncounter.Current.BattleSimulation != null && (PlayerEncounter.BattleState == BattleState.AttackerVictory || PlayerEncounter.BattleState == BattleState.DefenderVictory))
		{
			if (mapEvent.WinningSide == PlayerEncounter.Current.PlayerSide && PlayerEncounter.Battle.RetreatingSide == BattleSideEnum.None)
			{
				PlayerEncounter.EnemySurrender = true;
			}
			else
			{
				int totalManCount = MobileParty.MainParty.MemberRoster.TotalManCount;
				int totalWounded = MobileParty.MainParty.MemberRoster.TotalWounded;
				if (totalManCount - totalWounded == 0)
				{
					PlayerEncounter.PlayerSurrender = true;
				}
			}
			encounterState = PlayerEncounterState.PrepareResults;
		}
		else if (mapEvent != null && mapEvent.HasWinner)
		{
			encounterState = PlayerEncounterState.PrepareResults;
		}
		else if (mapEvent != null && mapEvent.IsNavalMapEvent && mapEvent.WinningSide == BattleSideEnum.None && (mapEvent.PartiesOnSide(mapEvent.PlayerSide).AnyQ((MapEventParty x) => x.Party.Ships.Count == 0) || mapEvent.PartiesOnSide(mapEvent.PlayerSide.GetOppositeSide()).AnyQ((MapEventParty x) => x.Party.Ships.Count == 0)))
		{
			_isNavalEncounterFinishedWithDisengage = false;
			if (mapEvent.PartiesOnSide(mapEvent.PlayerSide).SumQ((MapEventParty x) => x.Party.Ships.Count) == 0)
			{
				mapEvent.SetOverrideWinner(mapEvent.PlayerSide.GetOppositeSide());
				encounterState = PlayerEncounterState.PrepareResults;
				return;
			}
			if (mapEvent.PartiesOnSide(mapEvent.PlayerSide.GetOppositeSide()).SumQ((MapEventParty x) => x.Party.Ships.Count) == 0)
			{
				mapEvent.SetOverrideWinner(mapEvent.PlayerSide);
				encounterState = PlayerEncounterState.PrepareResults;
				return;
			}
			List<MapEventParty> list = mapEvent.AttackerSide.Parties.ToList();
			list.AddRange(mapEvent.DefenderSide.Parties);
			if (MobileParty.MainParty.Ships.Count == 0)
			{
				PartyBase.MainParty.MapEventSide = null;
				PlayerEncounter.Finish();
				RaftStateChangeAction.ActivateRaftStateForParty(MobileParty.MainParty);
			}
			foreach (MapEventParty item in list)
			{
				if (item.Ships.Count != 0 || item.Party == PartyBase.MainParty)
				{
					continue;
				}
				item.Party.MapEventSide = null;
				if (item.Party.IsMobile)
				{
					if (!item.Party.MobileParty.HasNavalNavigationCapability && item.Party.MobileParty.HasLandNavigationCapability)
					{
						RaftStateChangeAction.ActivateRaftStateForParty(item.Party.MobileParty);
					}
					else if (!item.Party.MobileParty.HasLandNavigationCapability)
					{
						DestroyPartyAction.Apply(null, item.Party.MobileParty);
					}
				}
			}
			stateHandled = true;
		}
		else
		{
			stateHandled = true;
			if (PlayerEncounter.Current.IsJoinedBattle && Campaign.Current.CurrentMenuContext != null && Campaign.Current.CurrentMenuContext.GameMenu.StringId == "join_encounter")
			{
				PlayerEncounter.LeaveBattle();
			}
			if (mapEvent != null && mapEvent.IsHideoutBattle)
			{
				mapEvent.MapEventSettlement.Hideout.SetNextPossibleAttackTime(Campaign.Current.Models.HideoutModel.HideoutHiddenDuration);
			}
		}
	}

	public override void OnPlayerEncounterContinueBattle(CampaignBattleResult campaignBattleResult, out PlayerEncounterState nextEncounterState, out bool stateHandled)
	{
		nextEncounterState = PlayerEncounter.Current.EncounterState;
		stateHandled = false;
		if (base.MapEvent.IsNavalMapEvent)
		{
			MapEventComponentHelper.OnPlayerEncounterContinueNavalBattleCommon(base.MapEvent, campaignBattleResult, out nextEncounterState);
		}
		if (nextEncounterState == PlayerEncounter.Current.EncounterState)
		{
			base.MapEvent.ApplyGainedVariablesOnPlayerBattleContinues();
			base.MapEvent.SetOverrideWinner(BattleSideEnum.None);
			stateHandled = true;
		}
	}

	public override void UpdateMapEventSettlement()
	{
		Settlement settlement = null;
		PartyBase leaderParty = base.MapEvent.AttackerSide.LeaderParty;
		PartyBase leaderParty2 = base.MapEvent.DefenderSide.LeaderParty;
		if (leaderParty.Position.IsOnLand != leaderParty2.Position.IsOnLand || (leaderParty.Position.IsOnLand && (leaderParty == PartyBase.MainParty || leaderParty2 == PartyBase.MainParty)))
		{
			float settlementBeingNearFieldBattleRadius = Campaign.Current.Models.EncounterModel.GetSettlementBeingNearFieldBattleRadius;
			MobileParty mobileParty = leaderParty.MobileParty;
			PartyBase landParty = ((mobileParty != null && mobileParty.IsCurrentlyAtSea) ? leaderParty2 : leaderParty);
			Village village = SettlementHelper.FindNearestVillageToMobileParty(landParty.MobileParty, MobileParty.NavigationType.Default, (Settlement x) => x.Position.DistanceSquared(landParty.Position) < settlementBeingNearFieldBattleRadius * settlementBeingNearFieldBattleRadius);
			if (village != null)
			{
				settlement = village.Settlement;
				if (leaderParty.MobileParty.IsCurrentlyAtSea == leaderParty2.MobileParty.IsCurrentlyAtSea)
				{
					bool isCurrentlyAtSea = leaderParty.MobileParty.IsCurrentlyAtSea;
					MobileParty.NavigationType customCapability = ((!isCurrentlyAtSea) ? MobileParty.NavigationType.Default : MobileParty.NavigationType.Naval);
					if (Campaign.Current.Models.MapDistanceModel.GetDistance(leaderParty.MobileParty, settlement, isCurrentlyAtSea, customCapability, out var estimatedLandRatio) > settlementBeingNearFieldBattleRadius * 4f || Campaign.Current.Models.MapDistanceModel.GetDistance(leaderParty2.MobileParty, settlement, isCurrentlyAtSea, customCapability, out estimatedLandRatio) > settlementBeingNearFieldBattleRadius * 4f)
					{
						settlement = null;
					}
				}
			}
		}
		base.MapEventSettlement = settlement;
	}

	protected override MBList<Ship> GetAllAvailableSimulationShips(MapEventSide side)
	{
		MBList<Ship> mBList = new MBList<Ship>();
		if (base.MapEvent.IsNavalMapEvent)
		{
			foreach (MapEventParty party in side.Parties)
			{
				foreach (Ship ship in party.Ships)
				{
					mBList.Add(ship);
				}
			}
		}
		return mBList;
	}

	public override void UpdateShipSiegeEnginesListOfSide(MapEventSide side, MBList<(SiegeEngineType, Ship)> list)
	{
		if (!base.MapEvent.IsNavalMapEvent || SimulationContext == MapEvent.PowerCalculationContext.NavalRaid)
		{
			return;
		}
		for (int i = 0; i < side.SimulationShipList.Count; i++)
		{
			foreach (SiegeEngineType siegeEngine in side.SimulationShipList[i].GetSiegeEngines())
			{
				list.Add((siegeEngine, side.SimulationShipList[i]));
			}
		}
	}

	public override void OnPlayerEncounterFinalizeBattle()
	{
		if (base.MapEvent.HasWinner || base.MapEvent.DiplomaticallyFinished)
		{
			PlayerEncounter.Current.FinalizeBattleFromComponent();
		}
		else
		{
			PlayerEncounter.LeaveBattle();
		}
	}

	public override bool CanLootDefeatedPartyShips(out bool partiallyLootShips)
	{
		bool result = base.MapEvent.IsNavalMapEvent && base.MapEvent.RetreatingSide == BattleSideEnum.None;
		partiallyLootShips = !CanLootAll();
		return result;
	}

	private bool CanLootAll()
	{
		if (base.MapEvent.IsPlayerMapEvent)
		{
			return !_isNavalEncounterFinishedWithDisengage;
		}
		return true;
	}

	public override bool CanLootDefeatedPartyCasualties()
	{
		return CanLootAll();
	}

