using System.Collections.Generic;
using System.Linq;
using TaleWorlds.CampaignSystem.Encounters;
using TaleWorlds.CampaignSystem.Naval;
using TaleWorlds.CampaignSystem.Party;
using TaleWorlds.CampaignSystem.Settlements;
using TaleWorlds.Core;
using TaleWorlds.Library;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.MapEvents;

public abstract class MapEventComponent
{
	private bool _isFinished;

	public MapEvent MapEvent { get; private set; }

	[SaveableProperty(100)]
	public Settlement MapEventSettlement { get; protected set; }

	public abstract MapEvent.PowerCalculationContext SimulationContext { get; }

	protected virtual void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		collectedObjects.Add(MapEventSettlement);
	}

	internal static object AutoGeneratedGetMemberValueMapEventSettlement(object o)
	{
		return ((MapEventComponent)o).MapEventSettlement;
	}

	public abstract MapEvent.BattleTypes GetBattleType();

	public virtual void OnBeforeMapEventFinalize()
	{
	}

	public virtual void OnAddInvolvedParty(MapEventParty party, BattleSideEnum side)
	{
	}

	public virtual void OnRemoveInvolvedParty(MapEventParty party)
	{
	}

	public abstract void AddInsideSettlementParties();

	public virtual void AddNearbyPartiesToPlayerMapEvent()
	{
	}

	public virtual void AddMapEventParties()
	{
	}

	public abstract CampaignVec2 GetMapEventPosition();

	public abstract void UpdateMapEventSettlement();

	public MBList<Ship> GetSimulationShipList(MapEventSide side)
	{
		MBList<Ship> allAvailableSimulationShips = GetAllAvailableSimulationShips(side);
		float num = side.NumRemainingSimulationTroops;
		allAvailableSimulationShips = allAvailableSimulationShips.OrderByDescending((Ship x) => Campaign.Current.Models.CombatSimulationModel.GetShipCombatImportance(x)).ToMBList();
		for (int num2 = 0; num2 < allAvailableSimulationShips.Count; num2++)
		{
			float num3 = (float)allAvailableSimulationShips[num2].MainDeckCrewCapacity * 0.8f;
			num -= num3;
			if (num <= 0f && allAvailableSimulationShips.Count - num2 - 1 > 0)
			{
				allAvailableSimulationShips.RemoveRange(num2 + 1, allAvailableSimulationShips.Count - num2 - 1);
				break;
			}
		}
		return allAvailableSimulationShips;
	}

	protected virtual MBList<Ship> GetAllAvailableSimulationShips(MapEventSide side)
	{
		return new MBList<Ship>();
	}

	public virtual void UpdateShipSiegeEnginesListOfSide(MapEventSide side, MBList<(SiegeEngineType, Ship)> list)
	{
	}

	public virtual bool CanLootDefeatedPartyShips(out bool partiallyLootShips)
	{
		partiallyLootShips = false;
		return false;
	}

	public virtual bool CanLootDefeatedPartyCasualties()
	{
		return true;
	}

	public virtual bool CanLootDefeatedPartyItems()
	{
		return true;
	}

	public virtual bool CanLootDefeatedPartyPrisoners()
	{
		return true;
	}

	public virtual bool CanCaptureDefeatedPartyMembers()
	{
		return true;
	}

	public virtual bool CanLootGold()
	{
		return true;
	}

	public abstract bool CheckIfBattleShouldContinueAfterBattleMission(CampaignBattleResult campaignBattleResult);

	public abstract void UpdatePlayerEncounterState(CampaignBattleResult campaignBattleResult, out PlayerEncounterState nextEncounterState, out bool stateHandled);

	public abstract void OnPlayerEncounterContinueBattle(CampaignBattleResult campaignBattleResult, out PlayerEncounterState nextEncounterState, out bool stateHandled);

	public abstract void OnPlayerEncounterFinalizeBattle();

	public abstract bool TryHandlePlayerEncounterEnd(bool playerIsAttacker);

	public abstract PlayerEncounterState GetPlayerEncounterStateOnMapEventEnd();

	protected MapEventComponent(MapEvent mapEvent)
	{
		MapEvent = mapEvent;
	}

	internal void AfterLoad(MapEvent mapEvent)
	{
		MapEvent = mapEvent;
		if (!mapEvent.IsFinalized)
		{
			_ = MapEventSettlement;
			UpdateMapEventSettlement();
		}
		OnAfterLoad();
	}

	public void InitializeComponent()
	{
		OnInitialize();
	}

	internal void FinalizeComponent()
	{
		if (!_isFinished)
		{
			FinishComponent();
		}
		OnFinalize();
	}

	internal void FinishComponent()
	{
		_isFinished = true;
		OnFinish();
	}

	protected virtual void OnInitialize()
	{
	}

	protected virtual void OnFinalize()
	{
	}

	public virtual void OnPartyAdded(PartyBase party)
	{
	}

	protected virtual void OnFinish()
	{
	}

	public virtual void Update(ref bool finish)
	{
	}

	public virtual void OnAfterLoad()
	{
	}

	public virtual void UpdateAfterMapChange(MobileParty.NavigationType leaderNavigationCapability, MapEvent mapEvent)
	{
	}
}
