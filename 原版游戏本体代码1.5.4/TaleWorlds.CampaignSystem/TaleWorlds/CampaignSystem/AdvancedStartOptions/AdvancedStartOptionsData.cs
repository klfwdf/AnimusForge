using System.Collections.Generic;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.AdvancedStartOptions;

public class AdvancedStartOptionsData
{
	[SaveableField(0)]
	private List<AdvancedStartData> _options;

	public AdvancedStartOptionsData(List<AdvancedStartData> options)
	{
		_options = options;
	}

	public AdvancedStartOptionsData()
	{
		_options = new List<AdvancedStartData>();
	}

	public AdvancedStartData GetOption(string key)
	{
		for (int i = 0; i < _options.Count; i++)
		{
			if (_options[i].StringId == key)
			{
				return _options[i];
			}
		}
		return null;
	}

	private bool HasValue(string key, out AdvancedStartData option)
	{
		option = GetOption(key);
		return option != null;
	}

	public bool HasValue(string key)
	{
		AdvancedStartData option;
		return HasValue(key, out option);
	}

	public T GetValue<T>(string key)
	{
		if (HasValue(key, out var option) && option is AdvancedStartData<T> advancedStartData)
		{
			return advancedStartData.Value;
		}
		return default(T);
	}

	public bool AddData(AdvancedStartData data)
	{
		if (HasValue(data.StringId, out var _))
		{
			return false;
		}
		_options.Add(data);
		return true;
	}

	public TextObject GetDisplayName(string key)
	{
		if (HasValue(key, out var option))
		{
			return option.GetDisplayName();
		}
		return TextObject.GetEmpty();
	}

	public IReadOnlyList<AdvancedStartData> GetOptions()
	{
		return _options;
	}

	public bool IsEmpty()
	{
		return _options.Count == 0;
	}

	internal static void AutoGeneratedStaticCollectObjectsAdvancedStartOptionsData(object o, List<object> collectedObjects)
	{
		((AdvancedStartOptionsData)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected virtual void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		collectedObjects.Add(_options);
	}

	internal static object AutoGeneratedGetMemberValue_options(object o)
	{
		return ((AdvancedStartOptionsData)o)._options;
	}
}
