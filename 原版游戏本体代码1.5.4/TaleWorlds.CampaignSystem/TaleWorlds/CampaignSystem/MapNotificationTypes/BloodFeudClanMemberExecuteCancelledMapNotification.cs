using System.Collections.Generic;
using TaleWorlds.Core;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.MapNotificationTypes;

public class BloodFeudClanMemberExecuteCancelledMapNotification : InformationData
{
	[SaveableProperty(1)]
	public Hero CaptiveHero { get; private set; }

	public override TextObject TitleText => new TextObject("{=cbVajmuo}Clan Member Got Released");

	public override string SoundEventPath => "event:/ui/notification/ransom_offer";

	internal static void AutoGeneratedStaticCollectObjectsBloodFeudClanMemberExecuteCancelledMapNotification(object o, List<object> collectedObjects)
	{
		((BloodFeudClanMemberExecuteCancelledMapNotification)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected override void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		base.AutoGeneratedInstanceCollectObjects(collectedObjects);
		collectedObjects.Add(CaptiveHero);
	}

	internal static object AutoGeneratedGetMemberValueCaptiveHero(object o)
	{
		return ((BloodFeudClanMemberExecuteCancelledMapNotification)o).CaptiveHero;
	}

	public BloodFeudClanMemberExecuteCancelledMapNotification(Hero captiveHero, TextObject descriptionText)
		: base(descriptionText)
	{
		CaptiveHero = captiveHero;
	}

	public BloodFeudClanMemberExecuteCancelledMapNotification(TextObject description)
		: base(description)
	{
	}

	public override bool IsValid()
	{
		return CaptiveHero.IsAlive;
	}
}
