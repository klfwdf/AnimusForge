using System.Collections.Generic;
using TaleWorlds.Core;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.MapNotificationTypes;

public class BloodFeudClanMemberGotExecutedMapNotification : InformationData
{
	[SaveableProperty(1)]
	public Hero ExecutedHero { get; private set; }

	[SaveableProperty(2)]
	public Hero ExecutingHero { get; private set; }

	[SaveableProperty(3)]
	public CampaignTime ExecutionDate { get; private set; }

	public override TextObject TitleText => new TextObject("{=MNEnRBg8}Clan Member Got Executed");

	public override string SoundEventPath => "event:/ui/notification/death";

	internal static void AutoGeneratedStaticCollectObjectsBloodFeudClanMemberGotExecutedMapNotification(object o, List<object> collectedObjects)
	{
		((BloodFeudClanMemberGotExecutedMapNotification)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected override void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		base.AutoGeneratedInstanceCollectObjects(collectedObjects);
		collectedObjects.Add(ExecutedHero);
		collectedObjects.Add(ExecutingHero);
		CampaignTime.AutoGeneratedStaticCollectObjectsCampaignTime(ExecutionDate, collectedObjects);
	}

	internal static object AutoGeneratedGetMemberValueExecutedHero(object o)
	{
		return ((BloodFeudClanMemberGotExecutedMapNotification)o).ExecutedHero;
	}

	internal static object AutoGeneratedGetMemberValueExecutingHero(object o)
	{
		return ((BloodFeudClanMemberGotExecutedMapNotification)o).ExecutingHero;
	}

	internal static object AutoGeneratedGetMemberValueExecutionDate(object o)
	{
		return ((BloodFeudClanMemberGotExecutedMapNotification)o).ExecutionDate;
	}

	public BloodFeudClanMemberGotExecutedMapNotification(Hero executedHero, Hero executingHero, CampaignTime executionDate, TextObject descriptionText)
		: base(descriptionText)
	{
		ExecutedHero = executedHero;
		ExecutingHero = executingHero;
		ExecutionDate = executionDate;
	}

	public BloodFeudClanMemberGotExecutedMapNotification(TextObject description)
		: base(description)
	{
	}
}
