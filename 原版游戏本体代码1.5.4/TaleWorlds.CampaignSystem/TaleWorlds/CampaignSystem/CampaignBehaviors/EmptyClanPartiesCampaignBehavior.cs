using System.Collections.Generic;
using Helpers;
using TaleWorlds.CampaignSystem.Actions;
using TaleWorlds.CampaignSystem.Naval;
using TaleWorlds.CampaignSystem.Party;
using TaleWorlds.CampaignSystem.Party.PartyComponents;
using TaleWorlds.CampaignSystem.Settlements;
using TaleWorlds.Core;
using TaleWorlds.Library;
using TaleWorlds.LinQuick;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.CampaignBehaviors;

public class EmptyClanPartiesCampaignBehavior : CampaignBehaviorBase, IEmptyClanPartiesCampaignBehavior
{
	public class EmptyClanPartiesCampaignBehaviorTypeDefiner : SaveableTypeDefiner
	{
		public EmptyClanPartiesCampaignBehaviorTypeDefiner()
			: base(312280)
		{
		}

		protected override void DefineStructTypes()
		{
			AddStructDefinition(typeof(EmptyClanParty), 1);
		}

		protected override void DefineContainerDefinitions()
		{
			ConstructContainerDefinition(typeof(List<EmptyClanParty>));
		}
	}

	internal struct EmptyClanParty
	{
		[SaveableField(0)]
		public readonly Hero Leader;

		[SaveableField(1)]
		public List<Ship> Ships;

		public EmptyClanParty(Hero leader)
		{
			Leader = leader;
			Ships = new List<Ship>();
		}

		public static void AutoGeneratedStaticCollectObjectsEmptyClanParty(object o, List<object> collectedObjects)
		{
			((EmptyClanParty)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
		}

		private void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
		{
			collectedObjects.Add(Leader);
			collectedObjects.Add(Ships);
		}

		internal static object AutoGeneratedGetMemberValueLeader(object o)
		{
			return ((EmptyClanParty)o).Leader;
		}

		internal static object AutoGeneratedGetMemberValueShips(object o)
		{
			return ((EmptyClanParty)o).Ships;
		}
	}

	private List<EmptyClanParty> _emptyClanParties = new List<EmptyClanParty>();

	public override void SyncData(IDataStore dataStore)
	{
		dataStore.SyncData("_emptyClanParties", ref _emptyClanParties);
	}

	public override void RegisterEvents()
	{
		CampaignEvents.MobilePartyDestroyed.AddNonSerializedListener(this, OnMobilePartyDestroyed);
		CampaignEvents.SettlementEntered.AddNonSerializedListener(this, OnSettlementEntered);
		CampaignEvents.BeforeHeroKilledEvent.AddNonSerializedListener(this, OnBeforeHeroKilled);
		CampaignEvents.MobilePartyCreated.AddNonSerializedListener(this, OnMobilePartyCreated);
		CampaignEvents.HeroPrisonerReleased.AddNonSerializedListener(this, OnHeroPrisonerReleased);
	}

	public void TransferCachedLordPartyToNewPartyForPlayerClan(Hero cachedPartyLeader, PartyBase newParty)
	{
		if (!TryGetEmptyClanPartyForHero(cachedPartyLeader, out var foundEmptyClanParty))
		{
			return;
		}
		RemoveEmptyClanParty(foundEmptyClanParty);
		foreach (Ship ship in foundEmptyClanParty.Ships)
		{
			ChangeShipOwnerAction.ApplyByTransferring(newParty, ship);
		}
	}

	public void DisbandCachedLordPartyForPlayerClan(Hero hero)
	{
		if (TryGetEmptyClanPartyForHero(hero, out var foundEmptyClanParty))
		{
			RemoveEmptyClanParty(foundEmptyClanParty);
			DistributePartyShipsAndRecoverGold(foundEmptyClanParty);
		}
	}

	public MBReadOnlyList<Ship> GetShipsForCachedLordPartyForPlayerClan(Hero hero)
	{
		MBReadOnlyList<Ship> result = null;
		foreach (EmptyClanParty emptyClanParty in _emptyClanParties)
		{
			if (emptyClanParty.Leader == hero)
			{
				result = emptyClanParty.Ships.ToMBList();
			}
		}
		return result;
	}

	public int GetShipCountForCachedLordPartyForPlayerClan(Hero hero)
	{
		int result = 0;
		foreach (EmptyClanParty emptyClanParty in _emptyClanParties)
		{
			if (emptyClanParty.Leader == hero)
			{
				result = emptyClanParty.Ships.Count;
			}
		}
		return result;
	}

	public MBReadOnlyList<Hero> GetEmptyClanPartyLeaders()
	{
		MBList<Hero> mBList = new MBList<Hero>();
		foreach (EmptyClanParty emptyClanParty in _emptyClanParties)
		{
			mBList.Add(emptyClanParty.Leader);
		}
		return mBList;
	}

	private void OnBeforeHeroKilled(Hero victim, Hero killer, KillCharacterAction.KillCharacterActionDetail detail, bool showNotification)
	{
		if (victim.Clan == Clan.PlayerClan && !victim.IsHumanPlayerCharacter && TryGetEmptyClanPartyForHero(victim, out var foundEmptyClanParty))
		{
			RemoveEmptyClanParty(foundEmptyClanParty);
			DistributePartyShipsAndRecoverGold(foundEmptyClanParty);
		}
	}

	private void OnSettlementEntered(MobileParty party, Settlement settlement, Hero hero)
	{
		if (hero != null && party == null && settlement != null)
		{
			TryCreateNewClanMobilePartyFromCachedEmptyParties(hero, settlement);
		}
	}

	private void OnMobilePartyDestroyed(MobileParty party, PartyBase _)
	{
		Hero owner = party.Owner;
		if (owner == null || owner.Clan != Clan.PlayerClan || owner.IsHumanPlayerCharacter || owner.IsDead || party.IsCaravan || party.IsDisbanding)
		{
			return;
		}
		EmptyClanParty emptyClanParty = new EmptyClanParty(owner);
		AddEmptyClanParty(emptyClanParty);
		if (!party.IsCurrentlyAtSea && party.Ships.Count > 0)
		{
			int num = party.Ships.Count - 1;
			while (0 <= num)
			{
				Ship ship = party.Ships[num];
				ship.Owner = null;
				emptyClanParty.Ships.Add(ship);
				num--;
			}
		}
	}

	private void OnMobilePartyCreated(MobileParty party)
	{
		if (party.ActualClan != Clan.PlayerClan || party.LeaderHero == null || party.IsCaravan || party.IsMainParty)
		{
			return;
		}
		Hero leaderHero = party.LeaderHero;
		if (!TryGetEmptyClanPartyForHero(leaderHero, out var foundEmptyClanParty))
		{
			return;
		}
		RemoveEmptyClanParty(foundEmptyClanParty);
		foreach (Ship ship in foundEmptyClanParty.Ships)
		{
			ChangeShipOwnerAction.ApplyByTransferring(party.Party, ship);
		}
	}

	private void OnHeroPrisonerReleased(Hero hero, PartyBase party, IFaction faction, EndCaptivityDetail detail, bool showNotification)
	{
		if (detail == EndCaptivityDetail.Ransom && hero != null && hero.CurrentSettlement != null && !hero.CurrentSettlement.MapFaction.IsAtWarWith(hero.MapFaction))
		{
			TryCreateNewClanMobilePartyFromCachedEmptyParties(hero, hero.CurrentSettlement);
		}
	}

	private void TryCreateNewClanMobilePartyFromCachedEmptyParties(Hero hero, Settlement settlement)
	{
		if (hero == null || !hero.IsActive || hero.Clan != Clan.PlayerClan || hero.IsHumanPlayerCharacter || hero.PartyBelongedTo != null || !TryGetEmptyClanPartyForHero(hero, out var foundEmptyClanParty))
		{
			return;
		}
		RemoveEmptyClanParty(foundEmptyClanParty);
		MobileParty mobileParty = MobilePartyHelper.SpawnLordParty(hero, settlement);
		foreach (Ship ship in foundEmptyClanParty.Ships)
		{
			ChangeShipOwnerAction.ApplyByTransferring(mobileParty.Party, ship);
		}
	}

	private bool TryGetEmptyClanPartyForHero(Hero hero, out EmptyClanParty foundEmptyClanParty)
	{
		bool result = false;
		foundEmptyClanParty = default(EmptyClanParty);
		foreach (EmptyClanParty emptyClanParty in _emptyClanParties)
		{
			if (emptyClanParty.Leader == hero)
			{
				foundEmptyClanParty = emptyClanParty;
				result = true;
				break;
			}
		}
		return result;
	}

	private void AddEmptyClanParty(EmptyClanParty emptyClanParty)
	{
		_emptyClanParties.Add(emptyClanParty);
	}

	private void RemoveEmptyClanParty(EmptyClanParty emptyClanParty)
	{
		_emptyClanParties.Remove(emptyClanParty);
	}

	private void DistributePartyShipsAndRecoverGold(EmptyClanParty emptyClanParty)
	{
		for (int num = emptyClanParty.Ships.Count - 1; num >= 0; num--)
		{
			Ship shipToSend = emptyClanParty.Ships[num];
			if (Clan.PlayerClan.WarPartyComponents.AnyQ((WarPartyComponent x) => Campaign.Current.Models.ShipDistributionModel.CanSendShipToParty(shipToSend, x.MobileParty)))
			{
				bool doesPartyNeedShips;
				MobileParty clanPartyToGetAvailableShip = ShipHelper.GetClanPartyToGetAvailableShip(shipToSend, Clan.PlayerClan, out doesPartyNeedShips);
				if (clanPartyToGetAvailableShip != null && doesPartyNeedShips)
				{
					ChangeShipOwnerAction.ApplyByTransferring(clanPartyToGetAvailableShip.Party, shipToSend);
					emptyClanParty.Ships.RemoveAt(num);
				}
			}
		}
		if (emptyClanParty.Ships.Count > 0)
		{
			int amountToRecoverFromRemainingShipsAfterDistribution = ShipHelper.GetAmountToRecoverFromRemainingShipsAfterDistribution(emptyClanParty.Ships.ToMBList(), MobileParty.MainParty);
			MBTextManager.SetTextVariable("GOLD_AMOUNT", amountToRecoverFromRemainingShipsAfterDistribution);
			MBTextManager.SetTextVariable("LEADER_NAME", emptyClanParty.Leader.Name);
			MBTextManager.SetTextVariable("GOLD_ICON", "{=!}<img src=\"General\\Icons\\Coin@2x\" extend=\"6\">");
			MBInformationManager.AddQuickInformation(new TextObject("{=YaSnA9j0}{LEADER_NAME}'s party has disbanded. You recovered {GOLD_AMOUNT}{GOLD_ICON} from its ships."));
			GiveGoldAction.ApplyBetweenCharacters(null, Hero.MainHero, amountToRecoverFromRemainingShipsAfterDistribution);
		}
	}
}
