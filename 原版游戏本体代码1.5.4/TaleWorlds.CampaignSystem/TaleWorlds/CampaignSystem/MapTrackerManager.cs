using System.Collections.Generic;
using System.Linq;
using TaleWorlds.CampaignSystem.Map;
using TaleWorlds.CampaignSystem.Party;
using TaleWorlds.Core;
using TaleWorlds.Library;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;
using TaleWorlds.SaveSystem.Load;

namespace TaleWorlds.CampaignSystem;

public class MapTrackerManager
{
	[SaveableField(2)]
	private List<ITrackableCampaignObject> _manualTrackers = new List<ITrackableCampaignObject>();

	public IMapTrackersHandler Handler { get; set; }

	internal static void AutoGeneratedStaticCollectObjectsMapTrackerManager(object o, List<object> collectedObjects)
	{
		((MapTrackerManager)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected virtual void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		collectedObjects.Add(_manualTrackers);
	}

	internal static object AutoGeneratedGetMemberValue_manualTrackers(object o)
	{
		return ((MapTrackerManager)o)._manualTrackers;
	}

	public void AddMapTracker(ITrackableCampaignObject trackable)
	{
		if (!(trackable is MobileParty) && !(trackable is Army) && !(trackable is MapMarker))
		{
			Debug.FailedAssert("Trying to add an unsupported object! MapTrackerManager only supports MobileParty, Army and MapMarker.", "C:\\BuildAgent\\work\\mb3\\Source\\Bannerlord\\TaleWorlds.CampaignSystem\\MapTrackerManager.cs", "AddMapTracker", 30);
		}
		else if (!_manualTrackers.Contains(trackable))
		{
			_manualTrackers.Add(trackable);
			Refresh(trackable);
		}
	}

	public void RemoveMapTracker(ITrackableCampaignObject trackable)
	{
		if (!(trackable is MobileParty) && !(trackable is Army) && !(trackable is MapMarker))
		{
			Debug.FailedAssert("Trying to remove an unsupported object! MapTrackerManager only supports MobileParty, Army and MapMarker.", "C:\\BuildAgent\\work\\mb3\\Source\\Bannerlord\\TaleWorlds.CampaignSystem\\MapTrackerManager.cs", "RemoveMapTracker", 48);
		}
		else if (_manualTrackers.Contains(trackable))
		{
			_manualTrackers.Remove(trackable);
			Refresh(trackable);
		}
	}

	public void ForceRemoveTracker(ITrackableCampaignObject trackable)
	{
		if (!(trackable is MobileParty) && !(trackable is Army) && !(trackable is MapMarker))
		{
			Debug.FailedAssert("Trying to remove an unsupported object! MapTrackerManager only supports MobileParty, Army and MapMarker.", "C:\\BuildAgent\\work\\mb3\\Source\\Bannerlord\\TaleWorlds.CampaignSystem\\MapTrackerManager.cs", "ForceRemoveTracker", 66);
			return;
		}
		_manualTrackers.Remove(trackable);
		Handler?.OnTrackerRemoved(trackable);
	}

	private bool ShouldAutoAddTracker(ITrackableCampaignObject trackable)
	{
		if (trackable is MobileParty party)
		{
			return ShouldAutoAddTrackerForParty(party);
		}
		if (trackable is Army army)
		{
			return ShouldAutoAddTrackerForArmy(army);
		}
		if (trackable is MapMarker)
		{
			return false;
		}
		Debug.FailedAssert("Unsupported trackable type for auto-tracking", "C:\\BuildAgent\\work\\mb3\\Source\\Bannerlord\\TaleWorlds.CampaignSystem\\MapTrackerManager.cs", "ShouldAutoAddTracker", 92);
		return false;
	}

	[LoadInitializationCallback]
	private void OnLoad(MetaData metaData, ObjectLoadData objectLoadData)
	{
		if (!MBSaveLoad.IsUpdatingGameVersion || !(MBSaveLoad.LastLoadedGameVersion < ApplicationVersion.FromString("v1.5.0")))
		{
			return;
		}
		if (_manualTrackers == null)
		{
			_manualTrackers = new List<ITrackableCampaignObject>();
		}
		object memberValueBySaveId = objectLoadData.GetMemberValueBySaveId(1);
		if (memberValueBySaveId == null || !(memberValueBySaveId is List<MapMarker> list))
		{
			return;
		}
		foreach (MapMarker item in list)
		{
			_manualTrackers.Add(item);
		}
	}

	private bool ShouldAutoAddTrackerForParty(MobileParty party)
	{
		if (party.IsMainParty || party.IsMilitia || party.IsGarrison || party.IsVillager || party.IsBandit || party.IsPatrolParty || party.IsBanditBossParty || party.IsCurrentlyUsedByAQuest || !party.IsActive)
		{
			return false;
		}
		if (party.IsCaravan || party.IsLordParty)
		{
			return party.ActualClan == Clan.PlayerClan;
		}
		return false;
	}

	private bool ShouldAutoAddTrackerForArmy(Army army)
	{
		if (army.Kingdom == Hero.MainHero.MapFaction && !army.Parties.Contains(MobileParty.MainParty))
		{
			return !army.IsDispersing;
		}
		return false;
	}

	public MapMarker CreateMapMarker(Banner banner, TextObject name, Vec3 position, bool isVisibleOnMap, string questId)
	{
		MapMarker mapMarker = new MapMarker(banner, name, position, isVisibleOnMap, questId);
		Campaign.Current.VisualTrackerManager.RegisterObject(mapMarker);
		AddMapTracker(mapMarker);
		return mapMarker;
	}

	public void RemoveMapMarker(MapMarker mapMarker)
	{
		Campaign.Current.VisualTrackerManager.RemoveTrackedObject(mapMarker);
		RemoveMapTracker(mapMarker);
	}

	public void RemoveAllMapMarkersByQuestId(string questId)
	{
		foreach (MapMarker item in GetMapMarkersByQuestId(questId).ToList())
		{
			RemoveMapMarker(item);
		}
	}

	public IEnumerable<MapMarker> GetMapMarkersByQuestId(string questId)
	{
		return from m in _manualTrackers.OfType<MapMarker>()
			where m.QuestId == questId
			select m;
	}

	internal void Refresh(ITrackableCampaignObject trackable)
	{
		if (ShouldAutoAddTracker(trackable) || _manualTrackers.Contains(trackable))
		{
			Handler?.OnTrackerAdded(trackable);
		}
		else
		{
			Handler?.OnTrackerRemoved(trackable);
		}
	}

	public void ResetTrackers()
	{
		Handler?.ResetTrackers();
	}

	public List<ITrackableCampaignObject> GetAllTrackers()
	{
		List<ITrackableCampaignObject> list = new List<ITrackableCampaignObject>();
		MBReadOnlyList<MobileParty> all = MobileParty.All;
		for (int i = 0; i < all.Count; i++)
		{
			if (ShouldAutoAddTrackerForParty(all[i]))
			{
				list.Add(all[i]);
			}
		}
		Army[] array = Kingdom.All.SelectMany((Kingdom k) => k.Armies).ToArray();
		for (int num = 0; num < array.Length; num++)
		{
			if (ShouldAutoAddTrackerForArmy(array[num]))
			{
				list.Add(array[num]);
			}
		}
		list.AddRange(_manualTrackers);
		return list;
	}
}
