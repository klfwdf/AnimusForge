using System.Collections.Generic;
using Helpers;
using TaleWorlds.CampaignSystem.BattleWreckages;
using TaleWorlds.CampaignSystem.Party;
using TaleWorlds.CampaignSystem.Settlements;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;

namespace TaleWorlds.CampaignSystem.LogEntries;

public class WreckageCreatedLogEntry : LogEntry
{
	private const float WreckageCommentRangeMultiplier = 0.25f;

	public override CampaignTime KeepInHistoryTime => CampaignTime.Days(30f);

	[SaveableProperty(0)]
	private BattleWreckage _wreckage { get; set; }

	internal static void AutoGeneratedStaticCollectObjectsWreckageCreatedLogEntry(object o, List<object> collectedObjects)
	{
		((WreckageCreatedLogEntry)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected override void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		base.AutoGeneratedInstanceCollectObjects(collectedObjects);
		collectedObjects.Add(_wreckage);
	}

	internal static object AutoGeneratedGetMemberValue_wreckage(object o)
	{
		return ((WreckageCreatedLogEntry)o)._wreckage;
	}

	public WreckageCreatedLogEntry(BattleWreckage wreckage)
	{
		_wreckage = wreckage;
	}

	public override string ToString()
	{
		return "You investigated the remains of a battle.";
	}

	public override int GetAsRumor(Settlement settlement, out TextObject comment)
	{
		comment = TextObject.GetEmpty();
		float num = Campaign.Current.GetAverageDistanceBetweenClosestTwoTownsWithNavigationType(MobileParty.NavigationType.All) * 0.25f;
		if (Campaign.Current.Models.MapDistanceModel.GetDistance(settlement, in _wreckage.Position, isFromPort: false, MobileParty.NavigationType.All) >= num)
		{
			return 0;
		}
		if (_wreckage.IsInvestigated)
		{
			if (_wreckage.Position.IsOnLand)
			{
				if (_wreckage.WreckageTypeCategory == BattleWreckage.WreckageType.Small)
				{
					comment = new TextObject("{=Hq7xzqmq}So, whatever was left over from that fight between {WRECKAGE_VICTOR_NAME} and {WRECKAGE_DEFEATED_NAME} has been picked clean. No sense leaving good loot about, I suppose.");
				}
				else
				{
					comment = new TextObject("{=v3iyZWKq}So, the remains of that battle, where {WRECKAGE_VICTOR_NAME} whipped {WRECKAGE_DEFEATED_NAME}, seem to have been picked clean. No sense leaving good loot about, I suppose.");
				}
			}
			else
			{
				comment = new TextObject("{=BTnce6OE}There are some ships that have been out searching all that wreckage, out where {WRECKAGE_VICTOR_NAME} defeated {WRECKAGE_DEFEATED_NAME}. That's good news for any survivors, I suppose.");
			}
		}
		else if (_wreckage.Position.IsOnLand)
		{
			if (_wreckage.WreckageTypeCategory == BattleWreckage.WreckageType.Small)
			{
				comment = new TextObject("{=1PsfmmY5}There are still a few bodies lying about from that fight between {WRECKAGE_VICTOR_NAME} and {WRECKAGE_DEFEATED_NAME}. Probably some loot to be had, too.");
			}
			else
			{
				comment = new TextObject("{=JH37caDx}You can still see the bodies on the field where {WRECKAGE_VICTOR_NAME} had it out with {WRECKAGE_DEFEATED_NAME}. A fair amount of loot to be had there too, I imagine, if you don't mind a bit of blood and muck.");
			}
		}
		else
		{
			comment = new TextObject("{=N46eaKXb}There's still wreckage washing ashore from where {WRECKAGE_VICTOR_NAME} defeated {WRECKAGE_DEFEATED_NAME}. There might be some valuables in with all the flotsam.");
		}
		comment.SetTextVariable("WRECKAGE_VICTOR_NAME", GetWreckageBattleSideName(_wreckage, _wreckage.GetWinnerFaction(), settlement.MapFaction));
		comment.SetTextVariable("WRECKAGE_DEFEATED_NAME", GetWreckageBattleSideName(_wreckage, _wreckage.GetDefeatedFaction(), settlement.MapFaction));
		return 10;
	}

	private static TextObject GetWreckageBattleSideName(BattleWreckage wreckage, IFaction sideFaction, IFaction conversationFaction)
	{
		if (sideFaction.IsBanditFaction)
		{
			if (!wreckage.Position.IsOnLand)
			{
				return new TextObject("{=OpTyzPdb}those pirates");
			}
			return new TextObject("{=dThvSaza}those bandits");
		}
		if (sideFaction == conversationFaction && sideFaction.Culture == conversationFaction.Culture)
		{
			return new TextObject("{=bRXbbfUX}our lads");
		}
		return FactionHelper.GetTermUsedByOtherFaction(sideFaction, conversationFaction, pejorative: false);
	}

	public override void GetConversationScoreAndComment(Hero conversationHero, bool findString, out string comment, out ImportanceEnum score)
	{
		score = ImportanceEnum.Zero;
		comment = "";
		if (!conversationHero.IsNotable || conversationHero.CurrentSettlement == null)
		{
			return;
		}
		float num = Campaign.Current.GetAverageDistanceBetweenClosestTwoTownsWithNavigationType(MobileParty.NavigationType.All) * 0.25f;
		if (!(Campaign.Current.Models.MapDistanceModel.GetDistance(conversationHero.CurrentSettlement, in _wreckage.Position, isFromPort: false, MobileParty.NavigationType.All) <= num))
		{
			return;
		}
		if (_wreckage.WreckageTypeCategory == BattleWreckage.WreckageType.Small)
		{
			score = ImportanceEnum.Unimportant;
		}
		else if (_wreckage.WreckageTypeCategory == BattleWreckage.WreckageType.Normal)
		{
			score = ImportanceEnum.SlightlyImportant;
		}
		else if (_wreckage.WreckageTypeCategory == BattleWreckage.WreckageType.Epic)
		{
			score = ImportanceEnum.SomewhatImportant;
		}
		IFaction mapFaction = conversationHero.CurrentSettlement.MapFaction;
		TextObject wreckageBattleSideName = GetWreckageBattleSideName(_wreckage, _wreckage.GetWinnerFaction(), mapFaction);
		TextObject wreckageBattleSideName2 = GetWreckageBattleSideName(_wreckage, _wreckage.GetDefeatedFaction(), mapFaction);
		MBTextManager.SetTextVariable("WRECKAGE_VICTOR_NAME", wreckageBattleSideName);
		MBTextManager.SetTextVariable("WRECKAGE_DEFEATED_NAME", wreckageBattleSideName2);
		if (_wreckage.Position.IsOnLand)
		{
			if (_wreckage.IsInvestigated)
			{
				comment = "str_comment_battle_site_land_picked";
			}
			else
			{
				comment = "str_comment_battle_site_land_fresh";
			}
		}
		else if (_wreckage.IsInvestigated)
		{
			comment = "str_comment_battle_site_sea_picked";
		}
		else
		{
			comment = "str_comment_battle_site_sea_fresh";
		}
	}

	public override bool IsValid()
	{
		return _wreckage != null;
	}
}
