using System.Collections.Generic;
using Helpers;
using TaleWorlds.CampaignSystem.Extensions;
using TaleWorlds.CampaignSystem.Map;
using TaleWorlds.CampaignSystem.Party;
using TaleWorlds.CampaignSystem.Settlements;
using TaleWorlds.Core;
using TaleWorlds.Library;
using TaleWorlds.Localization;
using TaleWorlds.SaveSystem;
using TaleWorlds.SaveSystem.Load;

namespace TaleWorlds.CampaignSystem.Naval;

public class AnchorPoint : IInteractablePoint, ITrackableCampaignObject, ITrackableBase
{
	[SaveableField(4)]
	private CampaignVec2 _lastUsedDisembarkPosition;

	[SaveableField(6)]
	private Settlement _settlement;

	[SaveableField(7)]
	private CampaignVec2 _position;

	public MobileParty Owner { get; private set; }

	public bool IsMovingToPoint => !ArrivalTime.IsPast;

	public bool IsReady => true;

	[SaveableProperty(3)]
	public CampaignTime ArrivalTime { get; private set; } = CampaignTime.Zero;

	[SaveableProperty(5)]
	public bool IsDisabled { get; set; }

	public Settlement Settlement
	{
		get
		{
			if (_settlement == null || IsMovingToPoint)
			{
				return null;
			}
			return _settlement;
		}
		set
		{
			if (_settlement != value)
			{
				_settlement = value;
				if (_settlement != null)
				{
					_position = _settlement.PortPosition;
					SetLastUsedDisembarkPosition(_settlement.GatePosition);
					UpdateAnchorVisualTrackers();
				}
			}
		}
	}

	public CampaignVec2 Position
	{
		get
		{
			if (_position.IsValid() && IsMovingToPoint)
			{
				return CampaignVec2.Invalid;
			}
			return _position;
		}
		set
		{
			if (_position != value)
			{
				_position = value;
				_settlement = null;
				UpdateAnchorVisualTrackers();
			}
		}
	}

	public bool IsValid => Position.IsValid();

	public bool IsAnchoredAtSettlement => Settlement != null;

	public TextObject Name
	{
		get
		{
			if (Owner.LeaderHero != null)
			{
				TextObject textObject = new TextObject("{=MTuvy9kd}{TROOP.NAME}{.o} Fleet");
				textObject.SetCharacterProperties("TROOP", Owner.LeaderHero.CharacterObject);
				return textObject;
			}
			return new TextObject("{=p6QNVu8p}Fleet");
		}
	}

	internal static void AutoGeneratedStaticCollectObjectsAnchorPoint(object o, List<object> collectedObjects)
	{
		((AnchorPoint)o).AutoGeneratedInstanceCollectObjects(collectedObjects);
	}

	protected virtual void AutoGeneratedInstanceCollectObjects(List<object> collectedObjects)
	{
		CampaignVec2.AutoGeneratedStaticCollectObjectsCampaignVec2(_lastUsedDisembarkPosition, collectedObjects);
		collectedObjects.Add(_settlement);
		CampaignVec2.AutoGeneratedStaticCollectObjectsCampaignVec2(_position, collectedObjects);
		CampaignTime.AutoGeneratedStaticCollectObjectsCampaignTime(ArrivalTime, collectedObjects);
	}

	internal static object AutoGeneratedGetMemberValueArrivalTime(object o)
	{
		return ((AnchorPoint)o).ArrivalTime;
	}

	internal static object AutoGeneratedGetMemberValueIsDisabled(object o)
	{
		return ((AnchorPoint)o).IsDisabled;
	}

	internal static object AutoGeneratedGetMemberValue_lastUsedDisembarkPosition(object o)
	{
		return ((AnchorPoint)o)._lastUsedDisembarkPosition;
	}

	internal static object AutoGeneratedGetMemberValue_settlement(object o)
	{
		return ((AnchorPoint)o)._settlement;
	}

	internal static object AutoGeneratedGetMemberValue_position(object o)
	{
		return ((AnchorPoint)o)._position;
	}

	public AnchorPoint(MobileParty owner)
	{
		Owner = owner;
		_position = CampaignVec2.Invalid;
	}

	public AnchorPoint(AnchorPoint anchor)
	{
		Owner = anchor.Owner;
		Position = anchor.Position;
		_lastUsedDisembarkPosition = anchor._lastUsedDisembarkPosition;
		ArrivalTime = anchor.ArrivalTime;
		IsDisabled = anchor.IsDisabled;
		Settlement = anchor.Settlement;
	}

	public void CallFleet(Settlement settlement)
	{
		CampaignTime fleetTravelTimeToSettlement = Campaign.Current.Models.PartyTransitionModel.GetFleetTravelTimeToSettlement(Owner, settlement);
		if (fleetTravelTimeToSettlement != CampaignTime.Zero)
		{
			ArrivalTime = CampaignTime.Now + fleetTravelTimeToSettlement;
		}
		Settlement = settlement;
	}

	public void SetOwner(MobileParty owner)
	{
		Owner = owner;
	}

	public void InitializeOnLoad(MobileParty owner)
	{
		SetOwner(owner);
		if (!MBSaveLoad.IsUpdatingGameVersion || !MBSaveLoad.LastLoadedGameVersion.IsOlderThan(ApplicationVersion.FromString("v1.5.0.114472")) || !_position.IsValid())
		{
			return;
		}
		foreach (Settlement item in Settlement.All)
		{
			if (item.HasPort && item.PortPosition.Distance(_position) < Campaign.Current.Models.EncounterModel.NeededMaximumDistanceForEncounteringTown)
			{
				Settlement = item;
			}
		}
	}

	public bool IsInteractable()
	{
		if (IsValid && !IsDisabled)
		{
			if (IsAnchoredAtSettlement && Settlement.MapFaction.IsAtWarWith(Owner.MapFaction))
			{
				return Settlement.IsRaided;
			}
			return true;
		}
		return false;
	}

	public bool CanPartyInteract(MobileParty mobileParty, float dt)
	{
		if (mobileParty.IsMainParty && IsInteractable())
		{
			return mobileParty.Position.Distance(GetInteractionPosition(mobileParty)) < Campaign.Current.Models.EncounterModel.NeededMaximumLandDistanceForEncounteringMobileParty;
		}
		return false;
	}

	public void SetLastUsedDisembarkPosition(CampaignVec2 pos)
	{
		_lastUsedDisembarkPosition = pos;
	}

	public CampaignVec2 GetInteractionPosition(MobileParty interactingParty)
	{
		if (IsValid)
		{
			return _lastUsedDisembarkPosition;
		}
		return CampaignVec2.Invalid;
	}

	public void OnPartyInteraction(MobileParty mobileParty)
	{
		mobileParty.Ai.AiBehaviorInteractable = null;
		mobileParty.TargetPosition = Position;
		mobileParty.MoveTargetPoint = Position;
		mobileParty.SetSailAtPosition(Position);
	}

	internal void TryUpdatePlayerAnchorInfo()
	{
		if (ArrivalTime != CampaignTime.Zero && ArrivalTime.IsPast)
		{
			ArrivalTime = CampaignTime.Zero;
			UpdateAnchorVisualTrackers();
			InformationManager.DisplayMessage(new InformationMessage(new TextObject("{=qFAhDtrw}Your fleet has arrived at its destination.").ToString(), new Color(0f, 1f, 0f))
			{
				SoundEventPath = "event:/ui/panels/panel_call_fleet"
			});
		}
	}

	TextObject ITrackableBase.GetName()
	{
		return Name;
	}

	public Vec3 GetPosition()
	{
		return Position.AsVec3();
	}

	Banner ITrackableCampaignObject.GetBanner()
	{
		return Owner.Banner;
	}

	public bool IsAtSettlement(Settlement settlement)
	{
		return settlement == Settlement;
	}

	public bool IsTargetingSettlement(Settlement settlement)
	{
		if (IsMovingToPoint)
		{
			return settlement == _settlement;
		}
		return false;
	}

	public void CheckPositionsForMapChangeAndUpdateIfNeeded()
	{
		if (_position.IsValid() && !NavigationHelper.IsPositionValidForNavigationType(_position, MobileParty.NavigationType.Naval))
		{
			if (_settlement != null)
			{
				_position = _settlement.PortPosition;
				return;
			}
			CampaignVec2 closestNavMeshFaceCenterPositionForPosition = NavigationHelper.GetClosestNavMeshFaceCenterPositionForPosition(_position, Campaign.Current.Models.PartyNavigationModel.GetInvalidTerrainTypesForNavigationType(MobileParty.NavigationType.Naval));
			_position = NavigationHelper.FindReachablePointAroundPosition(closestNavMeshFaceCenterPositionForPosition, MobileParty.NavigationType.Naval, 8f, 1f);
		}
	}

	public void ResetPosition()
	{
		Position = CampaignVec2.Invalid;
		ArrivalTime = CampaignTime.Zero;
	}

	public CampaignVec2 GetTargetPosition()
	{
		if (!IsMovingToPoint)
		{
			return CampaignVec2.Invalid;
		}
		return _position;
	}

	private void UpdateAnchorVisualTrackers()
	{
		if (!Owner.IsMainParty)
		{
			return;
		}
		if (IsValid)
		{
			if (!Campaign.Current.VisualTrackerManager.CheckTracked(this))
			{
				Campaign.Current.VisualTrackerManager.RegisterObject(this);
			}
		}
		else if (Campaign.Current.VisualTrackerManager.CheckTracked(this))
		{
			Campaign.Current.VisualTrackerManager.RemoveTrackedObject(this);
		}
	}

	[LoadInitializationCallback]
	private void OnLoad(MetaData metaData, ObjectLoadData objectLoadData)
	{
		if (!MBSaveLoad.IsUpdatingGameVersion || !(MBSaveLoad.LastLoadedGameVersion < ApplicationVersion.FromString("v1.5.0.114472")))
		{
			return;
		}
		object propertyValueBySaveId = objectLoadData.GetPropertyValueBySaveId(2);
		if (propertyValueBySaveId != null && propertyValueBySaveId is CampaignVec2 position && !position.IsDefault() && position.ToVec2().IsValid)
		{
			_position = position;
			return;
		}
		object propertyValueBySaveId2 = objectLoadData.GetPropertyValueBySaveId(1);
		if (propertyValueBySaveId2 != null && propertyValueBySaveId2 is CampaignVec2 position2)
		{
			_position = position2;
		}
	}
}
